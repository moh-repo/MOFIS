#!/usr/bin/env node
/**
 * Regenerates scripts/security-codes.json from the backend's authority rules.
 *
 * The frontend guards routes with `pageCode` / `pageCodes` / `permission` strings
 * that must name authorities the backend actually checks — a route guarded by a
 * code the server never grants lets the user onto a page whose every request is
 * then refused with a 403 (see the 27 Aug 2026 plan, item 4.1). This file is the
 * list the menu validator checks those strings against.
 *
 * Sources, all read-only:
 *   - Backend/src/main/java/com/dilaw/mohe/config/MoheSecurityExpressions.java —
 *     every hasAuthority('PAGE.ACTION') literal in the shared SpEL fragments.
 *   - Backend/src/main/java/com/dilaw/mohe/** /*Controller.java — the few
 *     controllers that inline their own hasAuthority(...) instead of using a
 *     shared constant (notifications, UMS users).
 *
 * The page-code prefixes (the part before the dot) are derived from the codes.
 *
 * Run from Frontend: npm run gen-security-codes
 */

import { readFileSync, writeFileSync, readdirSync, statSync } from 'fs';
import { join, dirname, relative } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const backendJava = join(__dirname, '..', '..', 'Backend', 'src', 'main', 'java', 'com', 'dilaw', 'mohe');
const expressionsFile = join(backendJava, 'config', 'MoheSecurityExpressions.java');
const outFile = join(__dirname, 'security-codes.json');

const AUTHORITY_RE = /hasAuthority\('([A-Z0-9_]+\.[A-Z0-9_]+)'\)/g;

function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, files);
    else if (name.endsWith('Controller.java')) files.push(full);
  }
  return files;
}

try {
  const codes = new Set();
  const sources = {};

  const record = (file, text) => {
    const found = [];
    for (const m of text.matchAll(AUTHORITY_RE)) {
      codes.add(m[1]);
      found.push(m[1]);
    }
    if (found.length) sources[relative(join(__dirname, '..', '..'), file).replace(/\\/g, '/')] = [...new Set(found)].sort();
  };

  record(expressionsFile, readFileSync(expressionsFile, 'utf8'));
  for (const file of walk(backendJava)) {
    record(file, readFileSync(file, 'utf8'));
  }

  const permissions = [...codes].sort();
  const pageCodes = [...new Set(permissions.map((c) => c.split('.')[0]))].sort();

  const out = {
    _comment: 'Generated by scripts/gen-security-codes.mjs from the backend security rules. Do not edit by hand.',
    pageCodes,
    permissions,
    sources
  };
  writeFileSync(outFile, JSON.stringify(out, null, 2) + '\n');
  console.log(`security-codes.json: ${pageCodes.length} page codes, ${permissions.length} permissions from ${Object.keys(sources).length} files.`);
} catch (e) {
  console.error('Error:', e.message);
  process.exit(1);
}
