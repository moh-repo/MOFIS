package com.dilaw.mohe.report;

import com.dilaw.mohe.report.excel.ExcelExportService;
import com.dilaw.mohe.scope.AsUser;
import com.dilaw.mohe.ums.model.AdminTier;
import org.apache.poi.xssf.usermodel.XSSFSheet;
import org.apache.poi.xssf.usermodel.XSSFWorkbook;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;
import com.dilaw.mohe.report.ReportException;

import java.io.ByteArrayInputStream;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.IntStream;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * S-07 against the real accounts: a country clerk is capped and refused above
 * the cap (audited), a ministry administrator is not, and every workbook the
 * POI builder writes ends with the export line naming who took it and for
 * which attaché.
 */
@Tag("integration")
@SpringBootTest
@Transactional
class ExportGuardTest {

    public record Bean(int n, String name) {
        public int getN() { return n; }
        public String getName() { return name; }
    }

    @Autowired private ExportGuard guard;
    @Autowired private ExcelExportService excel;
    @Autowired private JdbcTemplate jdbc;
    @Autowired private jakarta.persistence.EntityManager em;

    private static List<Bean> beans(int count) {
        List<Bean> out = new ArrayList<>(count);
        IntStream.range(0, count).forEach(i -> out.add(new Bean(i, "row " + i)));
        return out;
    }

    @Test
    @DisplayName("the caps follow the tiers: clerks capped, ministry administrators not")
    void capsByTier() {
        assertThat(guard.capFor(AdminTier.COUNTRY_STAFF)).isEqualTo(5000);
        assertThat(guard.capFor(AdminTier.COUNTRY_ADMIN)).isEqualTo(20000);
        assertThat(guard.capFor(AdminTier.MINISTRY_STAFF)).isEqualTo(50000);
        assertThat(guard.capFor(AdminTier.MINISTRY_ADMIN)).isZero();
        assertThat(guard.capFor(AdminTier.SUPER_ADMIN)).isZero();
        assertThat(AsUser.call(AsUser.JO_ADMIN, () -> guard.currentCap())).isEqualTo(20000);
        assertThat(AsUser.call(AsUser.ADMIN, () -> guard.currentCap())).isZero();
        assertThat(guard.currentCap()).as("nobody signed in: a scheduled run").isZero();
    }

    @Test
    @DisplayName("a clerk's export over the cap is refused with a typed 422 and audited; the ministry admin's is not")
    void overCapRefused() {
        long jordanStaff = 14L;
        assertThatThrownBy(() -> AsUser.run(jordanStaff, () -> guard.enforce(5001)))
                .isInstanceOf(ReportException.class)
                .hasMessageContaining("5000")
                .asInstanceOf(org.assertj.core.api.InstanceOfAssertFactories.type(ReportException.class))
                .satisfies(ex -> {
                    // P7: not 403. Nothing was refused on permission grounds, and a 403
                    // makes the staff app reload the profile.
                    assertThat(ex.getCode()).isEqualTo(ReportException.Code.REPORT_EXPORT_ROW_CAP);
                    assertThat(ex.getCode().status().value()).isEqualTo(422);
                    assertThat(ex.getArgs()).containsExactly(5001, 5000);
                });
        em.flush();
        Integer audited = jdbc.queryForObject(
                "SELECT COUNT(*) FROM UMSCORE.UserActions WHERE UserId = ? AND [Action] = 'EXPORT_CAPPED'",
                Integer.class, jordanStaff);
        assertThat(audited).isEqualTo(1);
        AsUser.run(jordanStaff, () -> guard.enforce(5000));
        AsUser.run(AsUser.ADMIN, () -> guard.enforce(1_000_000));
        guard.enforce(1_000_000);
    }

    @Test
    @DisplayName("the export line names the account and its attaché, or the ministry, or the scheduled run")
    void watermarkText() {
        String jordan = AsUser.call(AsUser.JO_ADMIN, () -> guard.watermark());
        assertThat(jordan).startsWith("Exported by jo_admin on ").contains(" for ").doesNotContain("the Ministry");
        String ministry = AsUser.call(AsUser.ADMIN, () -> guard.watermark());
        assertThat(ministry).startsWith("Exported by admin on ").endsWith(" for the Ministry");
        assertThat(guard.watermark()).startsWith("Generated by MOHE on ").endsWith("(scheduled run)");
    }

    @Test
    @DisplayName("the POI builder refuses above the cap and stamps the workbook below it")
    void workbookThroughTheBuilder() throws Exception {
        long jordanStaff = 14L;
        String[] headers = {"N", "Name"};
        String[] fields = {"n", "name"};
        assertThatThrownBy(() -> AsUser.call(jordanStaff, () -> {
            try {
                return excel.buildWorkbook("Too big", headers, fields, beans(5001));
            } catch (java.io.IOException e) {
                throw new IllegalStateException(e);
            }
        })).isInstanceOf(ReportException.class);

        byte[] small = AsUser.call(AsUser.JO_ADMIN, () -> {
            try {
                return excel.buildWorkbook("Small", headers, fields, beans(3));
            } catch (java.io.IOException e) {
                throw new IllegalStateException(e);
            }
        });
        try (XSSFWorkbook wb = new XSSFWorkbook(new ByteArrayInputStream(small))) {
            XSSFSheet sheet = wb.getSheetAt(0);
            String last = sheet.getRow(sheet.getLastRowNum()).getCell(0).getStringCellValue();
            assertThat(last).startsWith("Exported by jo_admin on ");
            assertThat(sheet.getFooter().getLeft()).isEqualTo(last);
        }
    }
}
