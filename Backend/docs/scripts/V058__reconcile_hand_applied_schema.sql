/* The adhoc script added this FK WITH NOCHECK, which is why the live one is
   "untrusted". Created trusted here: on a fresh database there is nothing to
   violate, and on an existing one the check either passes or reports. */
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_TRAVEL_TICKET_FUNDING_SOURCE')
BEGIN
    ALTER TABLE MOHECORE.STUDENT_TRAVEL_TICKET WITH CHECK
        ADD CONSTRAINT FK_TRAVEL_TICKET_FUNDING_SOURCE
        FOREIGN KEY (FUNDING_SOURCE_ID) REFERENCES MOHECORE.LU_TRAVEL_FUNDING_SOURCE (FUNDING_SOURCE_ID);
    PRINT 'V058: added FK_TRAVEL_TICKET_FUNDING_SOURCE';
END
ELSE IF EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_TRAVEL_TICKET_FUNDING_SOURCE' AND is_not_trusted = 1)
BEGIN
    IF NOT EXISTS (SELECT 1 FROM MOHECORE.STUDENT_TRAVEL_TICKET t
                    WHERE t.FUNDING_SOURCE_ID IS NOT NULL
                      AND NOT EXISTS (SELECT 1 FROM MOHECORE.LU_TRAVEL_FUNDING_SOURCE l WHERE l.FUNDING_SOURCE_ID = t.FUNDING_SOURCE_ID))
    BEGIN
        ALTER TABLE MOHECORE.STUDENT_TRAVEL_TICKET WITH CHECK CHECK CONSTRAINT FK_TRAVEL_TICKET_FUNDING_SOURCE;
        PRINT 'V058: FK_TRAVEL_TICKET_FUNDING_SOURCE is now trusted';
    END
    ELSE PRINT 'V058: FK_TRAVEL_TICKET_FUNDING_SOURCE left untrusted — orphan FUNDING_SOURCE_ID values exist';
END
GO

