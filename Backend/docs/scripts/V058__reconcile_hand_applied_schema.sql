/*
    V058 — put every hand-applied column and table into the numbered run.

    Why this exists
    ---------------
    The August 2026 revision compared what the entities map against what the
    numbered scripts create, and found objects that exist on every environment
    we know of but in no script at all — or only in docs/scripts/adhoc/, which
    the runbook explicitly says is *not* part of the run list. A database built
    from V001..V057 on a clean server is therefore missing them, and V046 (which
    reads ApprovalRequests.CountryId, WAFAR_SPENDING.BENEFICIARY_TYPE and
    TRAVEL_TICKET_ID) fails on it with "invalid column name".

    Each definition below is taken from the live catalogue (sys.columns on the
    dev database, 27 Aug 2026), not from memory, so an existing environment gets
    "nothing to do" and a fresh one gets exactly what the others have.

    What it adds, and where it came from
    ------------------------------------
      ALERTCORE.ApprovalRequests.CountryId      INT NULL       read by V046, V047 — never created
      MOHECORE.WAFAR_SPENDING.PAYEE_NAME_AR     NVARCHAR(255)  hand-added
      MOHECORE.WAFAR_SPENDING.PAYEE_NAME_EN     VARCHAR(255)   hand-added
      MOHECORE.WAFAR_SPENDING.REJECTION_REASON  NVARCHAR(500)  hand-added
      MOHECORE.WAFAR_SPENDING.BENEFICIARY_TYPE  NVARCHAR(30)   adhoc/alter_wafar_spending_beneficiary_type.sql
      MOHECORE.WAFAR_SPENDING.TRAVEL_TICKET_ID  INT NULL       adhoc/alter_student_travel_ticket_costs_funding.sql
      MOHECORE.WAFAR_SPENDING_CATEGORY row 'TRAVEL_TICKET'     same adhoc script
      MOHECORE.LU_TRAVEL_FUNDING_SOURCE (+ 3 seed rows)        same adhoc script
      MOHECORE.STUDENT_TRAVEL_TICKET.FUNDING_SOURCE_ID, TOTAL_TICKET_COST   same adhoc script
      MOHECORE.STUDENT_TRAVEL_TICKET_FAMILY_MEMBER.TICKET_COST              same adhoc script
      MOHECORE.FIN_RECEIVED_WHOM_DOCUMENTS                     adhoc/create_fin_received_whom_documents.sql
      UMSCORE.Users.IsMinistryUser              BIT NOT NULL DEFAULT 0   hand-added; the tenant kill-switch
                                                (CountryScopeService keys on IsMinistryUser OR IsSuperAdmin)
      MOHECORE.MOHE_QUARTER.COUNTRY_ID          INT NULL       read by V021 and credited to it by four
                                                later headers; V021 only reads it

    The two adhoc ALTER/CREATE scripts are now superseded by this one (their
    README says so). They stay in the folder for the record.

    Idempotent: every statement checks before it acts.
    Needs QUOTED_IDENTIFIER ON for the filtered index (sqlcmd: pass -I).
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;
SET QUOTED_IDENTIFIER ON;
GO

