      * Type codes are zero-padded to two digits, so FULL_CODE is unambiguous.

    Idempotent: an account whose (segment, year, FULL_CODE) exists is left
    alone — names are never overwritten by a re-run. The level rename only
    happens while the levels still carry V041's seeded names.
    The V041 trigger validates parent, full code, width and postability.
    Needs QUOTED_IDENTIFIER ON (sqlcmd -I) and UTF-8 (-f 65001).
*/

