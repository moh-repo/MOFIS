-- LU_ACADEMIC_YEAR
IF OBJECT_ID('MOHECORE.LU_ACADEMIC_YEAR', 'U') IS NULL
BEGIN
    CREATE TABLE MOHECORE.LU_ACADEMIC_YEAR (
        ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        CODE NVARCHAR(10) NOT NULL,
        NAME_AR NVARCHAR(200) NOT NULL,
        NAME_EN NVARCHAR(200) NOT NULL,
        SORT_ORDER INT NOT NULL DEFAULT 0,
        IS_DELETED BIT NOT NULL DEFAULT 0
    );
    DECLARE @y INT = 2005;
    WHILE @y <= 2030
    BEGIN
        INSERT INTO MOHECORE.LU_ACADEMIC_YEAR (CODE, NAME_AR, NAME_EN, SORT_ORDER)
        VALUES (CAST(@y AS NVARCHAR(10)), CAST(@y AS NVARCHAR(10)), CAST(@y AS NVARCHAR(10)), @y - 2004);
        SET @y = @y + 1;
    END
END
GO

-- LU_SEMESTER_NUMBER
IF OBJECT_ID('MOHECORE.LU_SEMESTER_NUMBER', 'U') IS NULL
BEGIN
    CREATE TABLE MOHECORE.LU_SEMESTER_NUMBER (
        ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        CODE NVARCHAR(10) NOT NULL,
        NAME_AR NVARCHAR(200) NOT NULL,
        NAME_EN NVARCHAR(200) NOT NULL,
        SORT_ORDER INT NOT NULL DEFAULT 0,
        IS_DELETED BIT NOT NULL DEFAULT 0
    );
    DECLARE @s INT = 1;
    WHILE @s <= 12
    BEGIN
        INSERT INTO MOHECORE.LU_SEMESTER_NUMBER (CODE, NAME_AR, NAME_EN, SORT_ORDER)
        VALUES (CAST(@s AS NVARCHAR(10)), CAST(@s AS NVARCHAR(10)), CAST(@s AS NVARCHAR(10)), @s);
        SET @s = @s + 1;
    END
END
GO
