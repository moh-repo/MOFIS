-- Student parents, studying relatives, and death-while-studying case tables.
-- Run against MOHE database; idempotent where possible.

-- LU_DEATH_PROCEDURE
IF OBJECT_ID('MOHECORE.LU_DEATH_PROCEDURE', 'U') IS NULL
BEGIN
    CREATE TABLE MOHECORE.LU_DEATH_PROCEDURE (
        ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        CODE NVARCHAR(50) NOT NULL,
        NAME_AR NVARCHAR(200) NOT NULL,
        NAME_EN NVARCHAR(200) NOT NULL,
        SORT_ORDER INT NOT NULL DEFAULT 0,
        IS_DELETED BIT NOT NULL DEFAULT 0
    );
    INSERT INTO MOHECORE.LU_DEATH_PROCEDURE (CODE, NAME_AR, NAME_EN, SORT_ORDER) VALUES
        (N'NOTIFY_FAMILY', N'إبلاغ العائلة', N'Notify family', 1),
        (N'SUSPEND_PAYMENTS', N'إيقاف المدفوعات/البدلات', N'Suspend payments/allowance', 2),
        (N'NOTIFY_UNIVERSITY', N'إبلاغ الجامعة', N'Notify university', 3),
        (N'COLLECT_DEATH_CERT', N'جمع شهادة الوفاة', N'Collect death certificate', 4),
        (N'CLOSE_FINANCE', N'إغلاق الملف المالي', N'Close financial file', 5),
        (N'FINAL_REPORT', N'التقرير النهائي', N'Final report', 6);
END
GO

-- STUDENT_PARENT
IF OBJECT_ID('MOHECORE.STUDENT_PARENT', 'U') IS NULL
BEGIN
    CREATE TABLE MOHECORE.STUDENT_PARENT (
        PARENT_ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        STUDENT_ID INT NOT NULL,
        RELATIONSHIP_ID INT NOT NULL,
        PARENT_NAME NVARCHAR(255) NOT NULL,
        NATIONAL_ID NVARCHAR(50) NULL,
        OCCUPATION NVARCHAR(200) NULL,
        PHONE NVARCHAR(50) NULL,
        ADDRESS NVARCHAR(500) NULL,
        IS_ALIVE BIT NOT NULL DEFAULT 1,
        NOTES NVARCHAR(1000) NULL,
        CREATED_DATE DATETIME2 NULL DEFAULT GETDATE(),
        CREATED_BY NVARCHAR(100) NULL,
        MODIFIED_DATE DATETIME2 NULL,
        MODIFIED_BY NVARCHAR(100) NULL,
        IS_DELETED BIT NOT NULL DEFAULT 0,
        CONSTRAINT FK_STUDENT_PARENT_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES MOHECORE.STUDENT_DATA(STUDENT_ID),
        CONSTRAINT FK_STUDENT_PARENT_REL FOREIGN KEY (RELATIONSHIP_ID) REFERENCES MOHECORE.LU_FAMILY_RELATIONSHIP(REL_ID)
    );
    CREATE INDEX IX_STUDENT_PARENT_STUDENT ON MOHECORE.STUDENT_PARENT(STUDENT_ID) WHERE IS_DELETED = 0;
END
GO

-- STUDENT_RELATIVE
IF OBJECT_ID('MOHECORE.STUDENT_RELATIVE', 'U') IS NULL
BEGIN
    CREATE TABLE MOHECORE.STUDENT_RELATIVE (
        RELATIVE_ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        STUDENT_ID INT NOT NULL,
        RELATED_STUDENT_ID INT NOT NULL,
        RELATIONSHIP_ID INT NOT NULL,
        NOTES NVARCHAR(1000) NULL,
        CREATED_DATE DATETIME2 NULL DEFAULT GETDATE(),
        CREATED_BY NVARCHAR(100) NULL,
        MODIFIED_DATE DATETIME2 NULL,
        MODIFIED_BY NVARCHAR(100) NULL,
        IS_DELETED BIT NOT NULL DEFAULT 0,
        CONSTRAINT FK_STUDENT_RELATIVE_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES MOHECORE.STUDENT_DATA(STUDENT_ID),
        CONSTRAINT FK_STUDENT_RELATIVE_RELATED FOREIGN KEY (RELATED_STUDENT_ID) REFERENCES MOHECORE.STUDENT_DATA(STUDENT_ID),
        CONSTRAINT FK_STUDENT_RELATIVE_REL FOREIGN KEY (RELATIONSHIP_ID) REFERENCES MOHECORE.LU_FAMILY_RELATIONSHIP(REL_ID),
        CONSTRAINT UQ_STUDENT_RELATIVE UNIQUE (STUDENT_ID, RELATED_STUDENT_ID, RELATIONSHIP_ID)
    );
    CREATE INDEX IX_STUDENT_RELATIVE_STUDENT ON MOHECORE.STUDENT_RELATIVE(STUDENT_ID) WHERE IS_DELETED = 0;
END
GO

-- STUDENT_DEATH_CASE
IF OBJECT_ID('MOHECORE.STUDENT_DEATH_CASE', 'U') IS NULL
BEGIN
    CREATE TABLE MOHECORE.STUDENT_DEATH_CASE (
        DEATH_CASE_ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        STUDENT_ID INT NOT NULL,
        DATE_OF_DEATH DATE NOT NULL,
        LEVEL_AT_DEATH_ID INT NULL,
        STUDY_YEAR_AT_DEATH INT NULL,
        PLACE_OF_DEATH NVARCHAR(300) NULL,
        CAUSE NVARCHAR(500) NULL,
        REPORTED_DATE DATETIME2 NULL DEFAULT GETDATE(),
        REPORTED_BY NVARCHAR(100) NULL,
        CASE_STATUS NVARCHAR(20) NOT NULL DEFAULT N'OPEN',
        NOTES NVARCHAR(2000) NULL,
        CREATED_DATE DATETIME2 NULL DEFAULT GETDATE(),
        CREATED_BY NVARCHAR(100) NULL,
        MODIFIED_DATE DATETIME2 NULL,
        MODIFIED_BY NVARCHAR(100) NULL,
        IS_DELETED BIT NOT NULL DEFAULT 0,
        CONSTRAINT FK_STUDENT_DEATH_CASE_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES MOHECORE.STUDENT_DATA(STUDENT_ID),
        CONSTRAINT UQ_STUDENT_DEATH_CASE_STUDENT UNIQUE (STUDENT_ID)
    );
END
GO

-- STUDENT_DEATH_PROCEDURE_STEP
IF OBJECT_ID('MOHECORE.STUDENT_DEATH_PROCEDURE_STEP', 'U') IS NULL
BEGIN
    CREATE TABLE MOHECORE.STUDENT_DEATH_PROCEDURE_STEP (
        STEP_ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        DEATH_CASE_ID INT NOT NULL,
        PROCEDURE_ID INT NOT NULL,
        IS_COMPLETED BIT NOT NULL DEFAULT 0,
        COMPLETED_DATE DATETIME2 NULL,
        COMPLETED_BY NVARCHAR(100) NULL,
        NOTES NVARCHAR(1000) NULL,
        CONSTRAINT FK_DEATH_STEP_CASE FOREIGN KEY (DEATH_CASE_ID) REFERENCES MOHECORE.STUDENT_DEATH_CASE(DEATH_CASE_ID),
        CONSTRAINT FK_DEATH_STEP_PROC FOREIGN KEY (PROCEDURE_ID) REFERENCES MOHECORE.LU_DEATH_PROCEDURE(ID)
    );
    CREATE INDEX IX_DEATH_STEP_CASE ON MOHECORE.STUDENT_DEATH_PROCEDURE_STEP(DEATH_CASE_ID);
END
GO

-- Seed DECEASED study status if missing
IF NOT EXISTS (
    SELECT 1 FROM MOHECORE.STUDENT_STUDY_STATUS
    WHERE STUDENT_STUDY_STATUS_NAME_EN = N'Deceased'
       OR STUDENT_STUDY_STATUS_NAME = N'متوفى'
)
BEGIN
    INSERT INTO MOHECORE.STUDENT_STUDY_STATUS (STUDENT_STUDY_STATUS_NAME, STUDENT_STUDY_STATUS_NAME_EN, IS_ACTIVE)
    VALUES (N'متوفى', N'Deceased', 1);
END
