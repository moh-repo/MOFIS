-- To archive only active students, uncomment:
-- WHERE sd.IS_DELETED = 0 OR sd.IS_DELETED IS NULL
;

PRINT CONCAT('Rows copied into STUDENT_DATA_ARCH: ', @@ROWCOUNT);

COMMIT TRANSACTION;
GO
