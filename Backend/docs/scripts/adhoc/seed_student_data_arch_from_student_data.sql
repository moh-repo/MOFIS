/*
 * One-time data load: rebuild STUDENT_DATA_ARCH from the live STUDENT_DATA table.
 *
 * TRUNCATE clears the archive and resets the ID identity seed, then every STUDENT_DATA row
 * is copied in. The archive's own ID (surrogate identity) is generated fresh — it is NOT
 * inserted — while STUDENT_ID holds the real student id (so one student can later own many
 * archive rows). ARCHIVE_DATE / INSERTED_TO_ARCH_DATE are stamped now; PROFILE_SNAPSHOT and
 * QUERTER_IS are left empty because those are produced by the quarter create/close flow.
 *
 * Prerequisite: V012__restructure_student_data_arch.sql must already be applied (this script
 * relies on the ID / STUDENT_ID / INSERTED_TO_ARCH_DATE / PROFILE_SNAPSHOT columns).
 *
 * DESTRUCTIVE: it empties STUDENT_DATA_ARCH first. Re-runnable.
 */

SET NOCOUNT ON;
SET XACT_ABORT ON;
GO

BEGIN TRANSACTION;

/* 1. Empty the archive (resets the ID identity back to the seed). */
TRUNCATE TABLE MOHECORE.STUDENT_DATA_ARCH;

/* 2. Copy every live student row in. ID is omitted so the identity generates it. */
INSERT INTO MOHECORE.STUDENT_DATA_ARCH
(
    STUDENT_ID,
    STUDENT_NAME,
    STUDENT_COUNTRY_ID,
    STUDENT_GOV_ID,
    STUDENT_MUD_ID,
    STUDENT_DELEGATION_DECISION_YEAR,
    STUDENT_DEGREE_ID,
    STUDENT_MAJOR_ID,
    STUDENT_MAJOR_NAME,
    STUDENT_DELEGATE_DECISION_NO,
    STUDENT_STUDY_NO_OF_YEARS,
    STUDENT_CURRENT_LEVEL_ID,
    STUDENT_FIRST_RECEIPT_OF_DUE,
    STUDENT_AMOUNT,
    AMOUNT_CURRENCY,
    STUDENT_NOTE_1,
    STUDENT_NOTE_2,
    STUDENT_STUDY_STATUS_ID,
    STUDENT_AGENCY_TYPE_ID,
    STUDENT_MINISTRY_TYPE_ID,
    STUDENT_STUDY_TYPE_ID,
    STUDENT_UNIVERSITY_TYPE_ID,
    STUDENT_ADDED_QUARTER,
    STUDENT_LAST_QUARTER,
    CURRENT_QUARTER,
    STUDENT_AGE,
    STUDY_UNIVERSITY_IN,
    STUDY_COLLEGE_IN,
    STUDY_COUNTRY_IN,
    SYUDY_GOV_IN,
    STUDY_EDUCATION_IN,
    STUDY_MAJOR_IN,
    STUDENT_BIRTHDATE,
    STUDENT_BIRTHDATE_PLACE,
    STUDENT_GENDER,
    STUDENT_PASSPORT_NUMBER,
    STUDENT_PASSPORT_ISSUE_DATE,
    STUDENT_PASSPORT_EXPIRE_DATE,
    STUDENT_PASSPORT_ISSUE_COUNTRY_ID,
    STUDY_UNIVERSITY_FEE_ID,
    STUDY_UNIVERSITY_FEE_STATUS_ID,
    UNIVERSITY_FEE_STATUS_CURRENCY,
    STUDENT_MIDATE,
    PICTURE_PATH,
    STUDENT_EMAIL,
    STUDENT_CELLPHONE,
    STUDENT_HOME_NUMBER,
    STUDENT_EMERGENCY_CONTACT,
    IS_DELETED,
    DELETED_DATE,
    RECORD_VISIBILITY,
    CREATED_ROLE_LEVEL,
    ARCHIVE_DATE,
    INSERTED_TO_ARCH_DATE,
    QUERTER_IS,
    PROFILE_SNAPSHOT
)
SELECT
    sd.STUDENT_ID,
    sd.STUDENT_NAME,
    sd.STUDENT_COUNTRY_ID,
    sd.STUDENT_GOV_ID,
    sd.STUDENT_MUD_ID,
    sd.STUDENT_DELEGATION_DECISION_YEAR,
    sd.STUDENT_DEGREE_ID,
    sd.STUDENT_MAJOR_ID,
    sd.STUDENT_MAJOR_NAME,
    sd.STUDENT_DELEGATE_DECISION_NO,
    sd.STUDENT_STUDY_NO_OF_YEARS,
    sd.STUDENT_CURRENT_LEVEL_ID,
    sd.STUDENT_FIRST_RECEIPT_OF_DUE,
    sd.STUDENT_AMOUNT,
    sd.AMOUNT_CURRENCY,
    sd.STUDENT_NOTE_1,
    sd.STUDENT_NOTE_2,
    sd.STUDENT_STUDY_STATUS_ID,
    sd.STUDENT_AGENCY_TYPE_ID,
    sd.STUDENT_MINISTRY_TYPE_ID,
    sd.STUDENT_STUDY_TYPE_ID,
    sd.STUDENT_UNIVERSITY_TYPE_ID,
    sd.STUDENT_ADDED_QUARTER,
    sd.STUDENT_LAST_QUARTER,
    sd.CURRENT_QUARTER,
    sd.STUDENT_AGE,
    sd.STUDY_UNIVERSITY_IN,
    sd.STUDY_COLLEGE_IN,
    sd.STUDY_COUNTRY_IN,
    sd.SYUDY_GOV_IN,
    sd.STUDY_EDUCATION_IN,
    sd.STUDY_MAJOR_IN,
    sd.STUDENT_BIRTHDATE,
    sd.STUDENT_BIRTHDATE_PLACE,
    sd.STUDENT_GENDER,
    sd.STUDENT_PASSPORT_NUMBER,
    sd.STUDENT_PASSPORT_ISSUE_DATE,
    sd.STUDENT_PASSPORT_EXPIRE_DATE,
    sd.STUDENT_PASSPORT_ISSUE_COUNTRY_ID,
    sd.STUDY_UNIVERSITY_FEE_ID,
    sd.STUDY_UNIVERSITY_FEE_STATUS_ID,
    sd.UNIVERSITY_FEE_STATUS_CURRENCY,
    sd.STUDENT_MIDATE,
    sd.PICTURE_PATH,
    sd.STUDENT_EMAIL,
    sd.STUDENT_CELLPHONE,
    sd.STUDENT_HOME_NUMBER,
    sd.STUDENT_EMERGENCY_CONTACT,
