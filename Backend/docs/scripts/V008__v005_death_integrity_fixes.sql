-- V008: V005 student death/family integrity fixes (idempotent)
-- Apply manually via SSMS when ready (see docs/MIGRATION_RUNBOOK.md)

-- FK: death case level at death
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_STUDENT_DEATH_CASE_LEVEL')
BEGIN
    ALTER TABLE MOHECORE.STUDENT_DEATH_CASE
        ADD CONSTRAINT FK_STUDENT_DEATH_CASE_LEVEL
        FOREIGN KEY (LEVEL_AT_DEATH_ID) REFERENCES MOHECORE.STUDENT_CURRENT_LEVEL(STUDENT_CURRENT_LEVEL_ID);
END
GO

-- Unique: one procedure step per case
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UQ_DEATH_STEP_CASE_PROCEDURE' AND object_id = OBJECT_ID('MOHECORE.STUDENT_DEATH_PROCEDURE_STEP'))
    ALTER TABLE MOHECORE.STUDENT_DEATH_PROCEDURE_STEP
        ADD CONSTRAINT UQ_DEATH_STEP_CASE_PROCEDURE UNIQUE (DEATH_CASE_ID, PROCEDURE_ID);
GO

-- Index: reverse lookup on student relatives
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_STUDENT_RELATIVE_RELATED' AND object_id = OBJECT_ID('MOHECORE.STUDENT_RELATIVE'))
    CREATE INDEX IX_STUDENT_RELATIVE_RELATED ON MOHECORE.STUDENT_RELATIVE (RELATED_STUDENT_ID)
        WHERE IS_DELETED = 0;
GO

-- ON DELETE CASCADE for death procedure steps when case is deleted
IF EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_DEATH_STEP_CASE')
BEGIN
    ALTER TABLE MOHECORE.STUDENT_DEATH_PROCEDURE_STEP DROP CONSTRAINT FK_DEATH_STEP_CASE;
    ALTER TABLE MOHECORE.STUDENT_DEATH_PROCEDURE_STEP
        ADD CONSTRAINT FK_DEATH_STEP_CASE
        FOREIGN KEY (DEATH_CASE_ID) REFERENCES MOHECORE.STUDENT_DEATH_CASE(DEATH_CASE_ID) ON DELETE CASCADE;
END
GO
