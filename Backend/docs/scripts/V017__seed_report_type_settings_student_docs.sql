/*
 * Seed REPORT_TYPE_SETTINGS rows for the four official single-student
 * documents so they appear in the report-settings admin screen
 * (/settings/report-settings) and ReportParamBuilder finds them by code.
 *
 * Titles/footer/signatories are deliberately left NULL: TITLE_01 falls back
 * to the system name from SYS_SETTINGS at render time, and the ministry
 * configures the official header lines and signatories through the UI.
 *
 * Idempotent — safe to re-run.
 */

IF NOT EXISTS (SELECT 1 FROM MOHECORE.REPORT_TYPE_SETTINGS WHERE REPORT_TYPE_CODE = 'STUDENT_ID_CARD')
BEGIN
    INSERT INTO MOHECORE.REPORT_TYPE_SETTINGS (REPORT_TYPE_CODE, REPORT_TYPE_NAME_AR, REPORT_TYPE_NAME_EN, IS_ACTIVE, SIGNATORY_COUNT)
    VALUES ('STUDENT_ID_CARD', N'بطاقة الطالب', 'Student ID Card', 1, 0);
END;

IF NOT EXISTS (SELECT 1 FROM MOHECORE.REPORT_TYPE_SETTINGS WHERE REPORT_TYPE_CODE = 'STUDENT_REGISTRATION_FORM')
BEGIN
    INSERT INTO MOHECORE.REPORT_TYPE_SETTINGS (REPORT_TYPE_CODE, REPORT_TYPE_NAME_AR, REPORT_TYPE_NAME_EN, IS_ACTIVE, SIGNATORY_COUNT)
    VALUES ('STUDENT_REGISTRATION_FORM', N'استمارة بيانات الطالب', 'Student Registration Form', 1, 0);
END;

IF NOT EXISTS (SELECT 1 FROM MOHECORE.REPORT_TYPE_SETTINGS WHERE REPORT_TYPE_CODE = 'ENROLLMENT_CERTIFICATE')
BEGIN
    INSERT INTO MOHECORE.REPORT_TYPE_SETTINGS (REPORT_TYPE_CODE, REPORT_TYPE_NAME_AR, REPORT_TYPE_NAME_EN, IS_ACTIVE, SIGNATORY_COUNT)
    VALUES ('ENROLLMENT_CERTIFICATE', N'شهادة قيد', 'Enrollment Certificate', 1, 1);
END;

IF NOT EXISTS (SELECT 1 FROM MOHECORE.REPORT_TYPE_SETTINGS WHERE REPORT_TYPE_CODE = 'STUDENT_FINANCIAL_STATEMENT')
BEGIN
    INSERT INTO MOHECORE.REPORT_TYPE_SETTINGS (REPORT_TYPE_CODE, REPORT_TYPE_NAME_AR, REPORT_TYPE_NAME_EN, IS_ACTIVE, SIGNATORY_COUNT)
    VALUES ('STUDENT_FINANCIAL_STATEMENT', N'كشف الحساب المالي للطالب', 'Student Financial Statement', 1, 0);
END;
