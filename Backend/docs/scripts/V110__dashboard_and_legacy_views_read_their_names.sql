    ((ROUND((SD.STUDENT_STUDY_NO_OF_YEARS * 4.0) / 3.0, 0) - 1) * SD.STUDENT_AMOUNT) AS STUDENT_ADDITIONAL_QUARTER_MONEY_ALL

