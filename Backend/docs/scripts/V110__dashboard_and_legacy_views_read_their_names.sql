    ISNULL(COALESCE(NULLIF(sdeg.STUDENT_DEGREE_NAME_EN, N''), sdeg.STUDENT_DEGREE_NAME), N'Unspecified') AS DegreeNameEn,

    COUNT(*) AS StudentCount,

