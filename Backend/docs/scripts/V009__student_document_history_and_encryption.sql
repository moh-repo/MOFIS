-- Student document encryption metadata + version history table.
-- Apply after V008 in SSMS against the MOHE database.

IF NOT EXISTS (
    SELECT 1 FROM sys.columns
    WHERE object_id = OBJECT_ID('MOHECORE.STUDENT_DOCUMENTS') AND name = 'FILE_HASH'
)
BEGIN
    ALTER TABLE MOHECORE.STUDENT_DOCUMENTS ADD FILE_HASH NVARCHAR(64) NULL;
END
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.columns
    WHERE object_id = OBJECT_ID('MOHECORE.STUDENT_DOCUMENTS') AND name = 'VERSION_NO'
)
BEGIN
    ALTER TABLE MOHECORE.STUDENT_DOCUMENTS ADD VERSION_NO INT NOT NULL
        CONSTRAINT DF_STUDENT_DOCUMENTS_VERSION_NO DEFAULT (1);
END
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.columns
    WHERE object_id = OBJECT_ID('MOHECORE.STUDENT_DOCUMENTS') AND name = 'IS_ENCRYPTED'
)
BEGIN
    ALTER TABLE MOHECORE.STUDENT_DOCUMENTS ADD IS_ENCRYPTED BIT NOT NULL
        CONSTRAINT DF_STUDENT_DOCUMENTS_IS_ENCRYPTED DEFAULT (0);
END
GO

IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = 'STUDENT_DOCUMENT_HISTORY' AND schema_id = SCHEMA_ID('MOHECORE'))
BEGIN
    CREATE TABLE MOHECORE.STUDENT_DOCUMENT_HISTORY (
        HISTORY_ID        INT IDENTITY(1,1) NOT NULL,
        DOCUMENT_ID       INT NOT NULL,
        STUDENT_ID        INT NOT NULL,
        DOCUMENT_NAME     NVARCHAR(500) NULL,
        DOCUMENT_TYPE     NVARCHAR(100) NULL,
        FILE_PATH         NVARCHAR(1000) NOT NULL,
        ORIGINAL_FILENAME NVARCHAR(500) NULL,
        FILE_SIZE         BIGINT NULL,
        FILE_HASH         NVARCHAR(64) NULL,
        VERSION_NO        INT NOT NULL,
        ACTION            NVARCHAR(20) NOT NULL,
        CHANGED_BY        BIGINT NULL,
        CHANGED_AT        DATETIME2 NOT NULL CONSTRAINT DF_STUDENT_DOCUMENT_HISTORY_CHANGED_AT DEFAULT (SYSUTCDATETIME()),
        CONSTRAINT PK_STUDENT_DOCUMENT_HISTORY PRIMARY KEY (HISTORY_ID)
    );
END
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = 'IX_STUDENT_DOCUMENT_HISTORY_DOCUMENT_ID'
      AND object_id = OBJECT_ID('MOHECORE.STUDENT_DOCUMENT_HISTORY')
)
BEGIN
    CREATE INDEX IX_STUDENT_DOCUMENT_HISTORY_DOCUMENT_ID
        ON MOHECORE.STUDENT_DOCUMENT_HISTORY (DOCUMENT_ID, VERSION_NO DESC);
END
GO

-- Audit trigger for history table (matches TR_Audit_STUDENT_DOCUMENTS pattern; do not use SP_CREATE_AUDIT_TRIGGERS_FOR_TABLE — it fails on sql_variant for this table).
IF NOT EXISTS (
    SELECT 1 FROM sys.triggers
    WHERE name = 'TR_Audit_STUDENT_DOCUMENT_HISTORY'
      AND parent_id = OBJECT_ID('MOHECORE.STUDENT_DOCUMENT_HISTORY')
)
BEGIN
    EXEC(N'
CREATE TRIGGER [MOHECORE].[TR_Audit_STUDENT_DOCUMENT_HISTORY]
ON [MOHECORE].[STUDENT_DOCUMENT_HISTORY]
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @Action NVARCHAR(50);
    DECLARE @UserId NVARCHAR(100);

    SET @UserId = CAST(SESSION_CONTEXT(N''UserId'') AS NVARCHAR(100));
    IF @UserId IS NULL SET @UserId = N''System'';

    IF EXISTS (SELECT 1 FROM inserted)
    BEGIN
        IF EXISTS (SELECT 1 FROM deleted)
            SET @Action = N''UPDATE'';
        ELSE
            SET @Action = N''INSERT'';
    END
    ELSE
        SET @Action = N''DELETE'';

    INSERT INTO [AUDITLOG].[AuditLogs] (TableName, RecordId, Action, OldValue, NewValue, ChangedBy, ChangedAt)
    SELECT
        N''STUDENT_DOCUMENT_HISTORY'',
        COALESCE(i.HISTORY_ID, d.HISTORY_ID),
        @Action,
        (SELECT h.[HISTORY_ID], h.[DOCUMENT_ID], h.[STUDENT_ID], h.[DOCUMENT_NAME], h.[DOCUMENT_TYPE],
                h.[FILE_PATH], h.[ORIGINAL_FILENAME], h.[FILE_SIZE], h.[FILE_HASH], h.[VERSION_NO],
                h.[ACTION], h.[CHANGED_BY], h.[CHANGED_AT]
         FROM deleted h
         WHERE h.HISTORY_ID = COALESCE(i.HISTORY_ID, d.HISTORY_ID)
         FOR JSON PATH, WITHOUT_ARRAY_WRAPPER),
        (SELECT h.[HISTORY_ID], h.[DOCUMENT_ID], h.[STUDENT_ID], h.[DOCUMENT_NAME], h.[DOCUMENT_TYPE],
                h.[FILE_PATH], h.[ORIGINAL_FILENAME], h.[FILE_SIZE], h.[FILE_HASH], h.[VERSION_NO],
                h.[ACTION], h.[CHANGED_BY], h.[CHANGED_AT]
         FROM inserted h
         WHERE h.HISTORY_ID = COALESCE(i.HISTORY_ID, d.HISTORY_ID)
         FOR JSON PATH, WITHOUT_ARRAY_WRAPPER),
        @UserId,
        GETDATE()
    FROM inserted i
    FULL OUTER JOIN deleted d ON i.HISTORY_ID = d.HISTORY_ID;
END
');
END
GO
