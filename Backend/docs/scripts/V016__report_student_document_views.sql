/*
 * Views backing the four official single-student documents
 * (ID Card, Registration Form, Enrollment Certificate, Financial Statement).
 *
 * V_STUDENT_PROFILE_DOC
 *   One row per (non-deleted) student with EVERY lookup FK resolved to a
 *   paired *_NAME_AR / *_NAME_EN column. All lookup joins are LEFT JOINs on
 *   purpose: a missing or inactive lookup row must never make a student
 *   disappear from their own document — it just prints an empty value.
 *   The EN column falls back to the Arabic name (NULLIF + COALESCE) because
 *   the legacy lookups are only partially translated.
 *
 * V_STUDENT_FINANCIAL_STATEMENT
 *   One row per finance record for a student: the archived quarter rows
 *   (STUDENT_FINANCE_ARCH — these carry the wafar and net the student had
 *   when the quarter closed) plus the live STUDENT_FINANCE row for the
 *   current quarter. The live row is suppressed when an archive row already
 *   exists for the same student + quarter so totals never double-count.
 *   ROW_KEY is a synthetic unique key for the JPA @Immutable mapping.
 *   Currency is only known on the live row (V014 added it to STUDENT_FINANCE
 *   only), so archive rows report NULL currency.
 *
 * Idempotent — safe to re-run (CREATE OR ALTER).
 */

CREATE OR ALTER VIEW MOHECORE.V_STUDENT_PROFILE_DOC
AS
SELECT
    sd.STUDENT_ID,
    sd.STUDENT_NAME,
    sd.PICTURE_PATH,
    sd.STUDENT_MIDATE,

    -- Personal
    sd.STUDENT_GENDER                              AS STUDENT_GENDER_ID,
    g.STUDENT_GENDER_NAME                          AS GENDER_NAME_AR,
    COALESCE(NULLIF(g.STUDENT_GENDER_NAME_EN, ''), g.STUDENT_GENDER_NAME) AS GENDER_NAME_EN,
    sd.STUDENT_BIRTHDATE,
    sd.STUDENT_BIRTHDATE_PLACE,
    sd.STUDENT_AGE,

    -- Home country / governorate / municipality
    sd.STUDENT_COUNTRY_ID,
    hc.STUDENT_COUNTRY_NAME                        AS HOME_COUNTRY_NAME_AR,
    COALESCE(NULLIF(hc.STUDENT_COUNTRY_NAME_EN, ''), hc.STUDENT_COUNTRY_NAME) AS HOME_COUNTRY_NAME_EN,
    sd.STUDENT_GOV_ID,
    hg.STUDENT_GOV_NAME                            AS HOME_GOV_NAME_AR,
    COALESCE(NULLIF(hg.STUDENT_GOV_NAME_EN, ''), hg.STUDENT_GOV_NAME)     AS HOME_GOV_NAME_EN,
    sd.STUDENT_MUD_ID,
    hm.STUDENT_MUD_NAME                            AS HOME_MUD_NAME_AR,
    COALESCE(NULLIF(hm.STUDENT_MUD_NAME_EN, ''), hm.STUDENT_MUD_NAME)     AS HOME_MUD_NAME_EN,

    -- Passport
    sd.STUDENT_PASSPORT_NUMBER,
    sd.STUDENT_PASSPORT_ISSUE_DATE,
    sd.STUDENT_PASSPORT_EXPIRE_DATE,
    sd.STUDENT_PASSPORT_ISSUE_COUNTRY_ID,
    pc.STUDENT_COUNTRY_NAME                        AS PASSPORT_COUNTRY_NAME_AR,
    COALESCE(NULLIF(pc.STUDENT_COUNTRY_NAME_EN, ''), pc.STUDENT_COUNTRY_NAME) AS PASSPORT_COUNTRY_NAME_EN,

    -- Academic
    sd.STUDENT_DEGREE_ID,
    deg.STUDENT_DEGREE_NAME                        AS DEGREE_NAME_AR,
    COALESCE(NULLIF(deg.STUDENT_DEGREE_NAME_EN, ''), deg.STUDENT_DEGREE_NAME) AS DEGREE_NAME_EN,
    sd.STUDENT_MAJOR_ID,
    COALESCE(NULLIF(maj.STUDENT_MAJOR_NAME, ''), sd.STUDENT_MAJOR_NAME)   AS MAJOR_NAME_AR,
    COALESCE(NULLIF(maj.STUDENT_MAJOR_NAME_EN, ''), NULLIF(maj.STUDENT_MAJOR_NAME, ''), sd.STUDENT_MAJOR_NAME) AS MAJOR_NAME_EN,
    sd.STUDENT_CURRENT_LEVEL_ID,
    lvl.STUDENT_CURRENT_LEVEL_NAME                 AS LEVEL_NAME_AR,
    COALESCE(NULLIF(lvl.STUDENT_CURRENT_LEVEL_NAME_EN, ''), lvl.STUDENT_CURRENT_LEVEL_NAME) AS LEVEL_NAME_EN,
    sd.STUDENT_STUDY_TYPE_ID,
    styp.STUDENT_STUDY_TYPE_NAME                   AS STUDY_TYPE_NAME_AR,
    COALESCE(NULLIF(styp.STUDENT_STUDY_TYPE_NAME_EN, ''), styp.STUDENT_STUDY_TYPE_NAME) AS STUDY_TYPE_NAME_EN,
    sd.STUDENT_STUDY_STATUS_ID,
    sst.STUDENT_STUDY_STATUS_NAME                  AS STUDY_STATUS_NAME_AR,
    COALESCE(NULLIF(sst.STUDENT_STUDY_STATUS_NAME_EN, ''), sst.STUDENT_STUDY_STATUS_NAME) AS STUDY_STATUS_NAME_EN,
    sd.STUDENT_UNIVERSITY_TYPE_ID,
    ut.STUDENT_UNIVERSITY_TYPE_NAME                AS UNIVERSITY_TYPE_NAME_AR,
    COALESCE(NULLIF(ut.STUDENT_UNIVERSITY_TYPE_NAME_EN, ''), ut.STUDENT_UNIVERSITY_TYPE_NAME) AS UNIVERSITY_TYPE_NAME_EN,
    sd.STUDENT_AGENCY_TYPE_ID,
    agt.STUDENT_AGENCY_TYPE_NAME                   AS AGENCY_TYPE_NAME_AR,
    COALESCE(NULLIF(agt.STUDENT_AGENCY_TYPE_NAME_EN, ''), agt.STUDENT_AGENCY_TYPE_NAME) AS AGENCY_TYPE_NAME_EN,
    sd.STUDENT_MINISTRY_TYPE_ID,
    mt.STUDENT_MINISTRY_TYPE_NAME                  AS MINISTRY_TYPE_NAME_AR,
    COALESCE(NULLIF(mt.STUDENT_MINISTRY_TYPE_NAME_EN, ''), mt.STUDENT_MINISTRY_TYPE_NAME) AS MINISTRY_TYPE_NAME_EN,
    sd.STUDENT_STUDY_NO_OF_YEARS,

    -- Delegation decision
    sd.STUDENT_DELEGATE_DECISION_NO,
    sd.STUDENT_DELEGATION_DECISION_YEAR,

    -- Study destination chain (note: STUDENT_DATA's gov-in FK column is the
    -- historical typo SYUDY_GOV_IN — keep it aliased, never renamed here)
    sd.STUDY_COUNTRY_IN                            AS STUDY_COUNTRY_IN_ID,
    ci.STUDY_COUNTRY_IN_NAME                       AS STUDY_COUNTRY_NAME_AR,
    COALESCE(NULLIF(ci.STUDY_COUNTRY_IN_NAME_EN, ''), ci.STUDY_COUNTRY_IN_NAME) AS STUDY_COUNTRY_NAME_EN,
    sd.SYUDY_GOV_IN                                AS STUDY_GOV_IN_ID,
    gi.STUDY_GOV_IN_NAME                           AS STUDY_GOV_NAME_AR,
    COALESCE(NULLIF(gi.STUDY_GOV_IN_NAME_EN, ''), gi.STUDY_GOV_IN_NAME)   AS STUDY_GOV_NAME_EN,
    sd.STUDY_UNIVERSITY_IN                         AS STUDY_UNIVERSITY_IN_ID,
    ui.STUDY_UNIVERSITY_IN_NAME                    AS STUDY_UNIVERSITY_NAME_AR,
    COALESCE(NULLIF(ui.STUDY_UNIVERSITY_IN_NAME_EN, ''), ui.STUDY_UNIVERSITY_IN_NAME) AS STUDY_UNIVERSITY_NAME_EN,
    sd.STUDY_COLLEGE_IN                            AS STUDY_COLLEGE_IN_ID,
    coli.STUDY_COLLEGE_IN_NAME                     AS STUDY_COLLEGE_NAME_AR,
    COALESCE(NULLIF(coli.STUDY_COLLEGE_IN_NAME_EN, ''), coli.STUDY_COLLEGE_IN_NAME) AS STUDY_COLLEGE_NAME_EN,
    sd.STUDY_EDUCATION_IN                          AS STUDY_EDUCATION_IN_ID,
    edi.STUDY_EDUCTION_NAME                        AS STUDY_EDUCATION_NAME_AR,
    COALESCE(NULLIF(edi.STUDY_EDUCTION_NAME_EN, ''), edi.STUDY_EDUCTION_NAME) AS STUDY_EDUCATION_NAME_EN,
    sd.STUDY_MAJOR_IN                              AS STUDY_MAJOR_IN_ID,
    smi.STUDY_MAJOR_NAME                           AS STUDY_MAJOR_IN_NAME_AR,
    COALESCE(NULLIF(smi.STUDY_MAJOR_NAME_EN, ''), smi.STUDY_MAJOR_NAME)   AS STUDY_MAJOR_IN_NAME_EN,

    -- Scholarship finance summary
    sd.STUDENT_AMOUNT,
    sd.AMOUNT_CURRENCY                             AS AMOUNT_CURRENCY_ID,
    cur.STUDY_CURRENCY_IN_NAME                     AS CURRENCY_NAME_AR,
    COALESCE(NULLIF(cur.STUDY_CURRENCY_IN_NAME_EN, ''), cur.STUDY_CURRENCY_IN_NAME) AS CURRENCY_NAME_EN,

    -- Contacts
    sd.STUDENT_EMAIL,
    sd.STUDENT_CELLPHONE,
    sd.STUDENT_HOME_NUMBER,
    sd.STUDENT_EMERGENCY_CONTACT,

    -- Quarters
    sd.STUDENT_ADDED_QUARTER,
    sd.STUDENT_LAST_QUARTER,
    sd.CURRENT_QUARTER
FROM MOHECORE.STUDENT_DATA sd
LEFT JOIN MOHECORE.STUDENT_GENDER          g    ON g.STUDENT_GENDER_ID = sd.STUDENT_GENDER
LEFT JOIN MOHECORE.STUDENT_COUNTRY         hc   ON hc.STUDENT_COUNTRY_ID = sd.STUDENT_COUNTRY_ID
LEFT JOIN MOHECORE.STUDENT_GOV             hg   ON hg.STUDENT_GOV_ID = sd.STUDENT_GOV_ID
LEFT JOIN MOHECORE.STUDENT_GOV_MUD         hm   ON hm.STUDENT_MUD_ID = sd.STUDENT_MUD_ID
LEFT JOIN MOHECORE.STUDENT_COUNTRY         pc   ON pc.STUDENT_COUNTRY_ID = sd.STUDENT_PASSPORT_ISSUE_COUNTRY_ID
LEFT JOIN MOHECORE.STUDENT_DEGREE          deg  ON deg.STUDENT_DEGREE_ID = sd.STUDENT_DEGREE_ID
LEFT JOIN MOHECORE.STUDENT_MAJOR           maj  ON maj.STUDENT_MAJOR_ID = sd.STUDENT_MAJOR_ID
LEFT JOIN MOHECORE.STUDENT_CURRENT_LEVEL   lvl  ON lvl.STUDENT_CURRENT_LEVEL_ID = sd.STUDENT_CURRENT_LEVEL_ID
LEFT JOIN MOHECORE.STUDENT_STUDY_TYPE      styp ON styp.STUDENT_STUDY_TYPE_ID = sd.STUDENT_STUDY_TYPE_ID
LEFT JOIN MOHECORE.STUDENT_STUDY_STATUS    sst  ON sst.STUDENT_STUDY_STATUS_ID = sd.STUDENT_STUDY_STATUS_ID
LEFT JOIN MOHECORE.STUDENT_UNIVERSITY_TYPE ut   ON ut.STUDENT_UNIVERSITY_TYPE_ID = sd.STUDENT_UNIVERSITY_TYPE_ID
LEFT JOIN MOHECORE.STUDENT_AGENCY_TYPE     agt  ON agt.STUDENT_AGENCY_TYPE_ID = sd.STUDENT_AGENCY_TYPE_ID
LEFT JOIN MOHECORE.STUDENT_MINISTRY_TYPE   mt   ON mt.STUDENT_MINISTRY_TYPE_ID = sd.STUDENT_MINISTRY_TYPE_ID
LEFT JOIN MOHECORE.STUDY_COUNTRY_IN        ci   ON ci.STUDY_COUNTRY_IN_ID = sd.STUDY_COUNTRY_IN
LEFT JOIN MOHECORE.STUDY_GOV_IN            gi   ON gi.STUDY_GOV_IN_ID = sd.SYUDY_GOV_IN
LEFT JOIN MOHECORE.STUDY_UNIVERSITY_IN     ui   ON ui.STUDY_UNIVERSITY_IN_ID = sd.STUDY_UNIVERSITY_IN
LEFT JOIN MOHECORE.STUDY_COLLEGE_IN        coli ON coli.STUDY_COLLEGE_IN_ID = sd.STUDY_COLLEGE_IN
LEFT JOIN MOHECORE.STUDY_EDUCTION_IN       edi  ON edi.STUDY_EDUCTION_ID = sd.STUDY_EDUCATION_IN
LEFT JOIN MOHECORE.STUDY_MAJOR_IN          smi  ON smi.STUDY_MAJOR_ID = sd.STUDY_MAJOR_IN
LEFT JOIN MOHECORE.STUDY_CURRENCY_IN       cur  ON cur.STUDY_CURRENCY_IN_ID = sd.AMOUNT_CURRENCY
WHERE (sd.IS_DELETED = 0 OR sd.IS_DELETED IS NULL);
GO

CREATE OR ALTER VIEW MOHECORE.V_STUDENT_FINANCIAL_STATEMENT
AS
WITH FIN_ROWS AS (
    -- Closed quarters: the archive keeps the amount/wafar/net as they were
    -- at quarter close, so these rows are read verbatim.
    SELECT
        CONCAT('A-', fa.FIN_ARCH_ENTRY_ID)         AS ROW_KEY,
        'ARCHIVE'                                  AS SOURCE_TYPE,
        fa.STUDENT_ID,
        fa.MOHE_QUARTER_ID,
        fa.STUDENT_FIN_RECIEVED_YEAR               AS RECEIVED_YEAR,
        fa.STUDENT_FIN_RECIEVED_MONTH              AS RECEIVED_MONTH,
        fa.STUDENT_FIN_RECIEVED_AMOUNT             AS RECEIVED_AMOUNT,
        fa.WAFAR_AMOUNT,
        fa.WAFAR_TYPE_ID,
        COALESCE(fa.NET_AMOUNT,
                 ISNULL(fa.STUDENT_FIN_RECIEVED_AMOUNT, 0) - ISNULL(fa.WAFAR_AMOUNT, 0)) AS NET_AMOUNT,
        CAST(NULL AS INT)                          AS CURRENCY_ID,
        fa.STUDY_FINANCE_BANKE_ID                  AS BANK_ID,
        fa.STUDY_FINANCE_BANK_BRANCH_ID            AS BANK_BRANCH_ID,
        fa.STUDY_FIN_RECIEVED_STATUS               AS RECEIVED_STATUS_ID,
        fa.STUDY_RECEIVED_WHOM_STATUS_ID           AS RECEIVED_WHOM_STATUS_ID,
        fa.STUDY_CHECK_ID,
        fa.STUDY_CHECK_DATE,
        fa.STUDY_CHECK_FORM_NUMBER
    FROM MOHECORE.STUDENT_FINANCE_ARCH fa

    UNION ALL

    -- Live (current-quarter) row — suppressed once the same quarter has been
    -- archived for the student, so statements never double-count a quarter.
    SELECT
        CONCAT('C-', sf.STUDENT_ID),
        'CURRENT',
        sf.STUDENT_ID,
        sf.MOHE_QUARTER_ID,
        sf.STUDENT_FIN_RECIEVED_YEAR,
        sf.STUDENT_FIN_RECIEVED_MONTH,
        sf.STUDENT_FIN_RECIEVED_AMOUNT,
        sf.WAFAR_AMOUNT,
        sf.WAFAR_TYPE_ID,
        COALESCE(sf.NET_AMOUNT,
                 ISNULL(sf.STUDENT_FIN_RECIEVED_AMOUNT, 0) - ISNULL(sf.WAFAR_AMOUNT, 0)),
        sf.STUDY_CURRENCY_IN_ID,
        sf.STUDY_FINANCE_BANKE_ID,
        sf.STUDY_FINANCE_BANK_BRANCH_ID,
        sf.STUDY_FIN_RECIEVED_STATUS,
        sf.STUDY_RECEIVED_WHOM_STATUS_ID,
        sf.STUDY_CHECK_ID,
        sf.STUDY_CHECK_DATE,
        sf.STUDY_CHECK_FORM_NUMBER
    FROM MOHECORE.STUDENT_FINANCE sf
    WHERE NOT EXISTS (
        SELECT 1 FROM MOHECORE.STUDENT_FINANCE_ARCH fa2
        WHERE fa2.STUDENT_ID = sf.STUDENT_ID
          AND fa2.MOHE_QUARTER_ID = sf.MOHE_QUARTER_ID
    )
)
SELECT
    fr.ROW_KEY,
    fr.SOURCE_TYPE,
    fr.STUDENT_ID,
    fr.MOHE_QUARTER_ID,
    q.QUARTER_YEAR,
    q.QUARTER_NO,
    q.QUARTER_NAME                                 AS QUARTER_NAME_AR,
    COALESCE(NULLIF(q.QUARTER_NAME_EN, ''), q.QUARTER_NAME) AS QUARTER_NAME_EN,
    fr.RECEIVED_YEAR,
    fr.RECEIVED_MONTH,
    fr.RECEIVED_AMOUNT,
    fr.WAFAR_AMOUNT,
    fr.WAFAR_TYPE_ID,
    wt.WAFAR_NAME                                  AS WAFAR_TYPE_NAME_AR,
    COALESCE(NULLIF(wt.WAFAR_NAME_EN, ''), wt.WAFAR_NAME) AS WAFAR_TYPE_NAME_EN,
    fr.NET_AMOUNT,
    fr.CURRENCY_ID,
    cur.STUDY_CURRENCY_IN_NAME                     AS CURRENCY_NAME_AR,
    COALESCE(NULLIF(cur.STUDY_CURRENCY_IN_NAME_EN, ''), cur.STUDY_CURRENCY_IN_NAME) AS CURRENCY_NAME_EN,
    fr.BANK_ID,
    bk.STUDY_FINANCE_BANKE_NAME                    AS BANK_NAME_AR,
    COALESCE(NULLIF(bk.STUDY_FINANCE_BANKE_NAME_EN, ''), bk.STUDY_FINANCE_BANKE_NAME) AS BANK_NAME_EN,
    fr.BANK_BRANCH_ID,
    bb.STUDY_FINANCE_BANK_BRANCH_NAME              AS BANK_BRANCH_NAME_AR,
    COALESCE(NULLIF(bb.STUDY_FINANCE_BANK_BRANCH_NAME_EN, ''), bb.STUDY_FINANCE_BANK_BRANCH_NAME) AS BANK_BRANCH_NAME_EN,
    fr.RECEIVED_STATUS_ID,
    rs.STUDY_FIN_RECEIVED_STATUS_NAME              AS RECEIVED_STATUS_NAME_AR,
    COALESCE(NULLIF(rs.STUDY_FIN_RECEIVED_STATUS_NAME_EN, ''), rs.STUDY_FIN_RECEIVED_STATUS_NAME) AS RECEIVED_STATUS_NAME_EN,
    fr.RECEIVED_WHOM_STATUS_ID,
    rws.STUDY_RECEIVED_WHOM_STATUS_NAME            AS RECEIVED_WHOM_STATUS_NAME_AR,
    COALESCE(NULLIF(rws.STUDY_RECEIVED_WHOM_STATUS_NAME_EN, ''), rws.STUDY_RECEIVED_WHOM_STATUS_NAME) AS RECEIVED_WHOM_STATUS_NAME_EN,
    fr.STUDY_CHECK_ID,
    fr.STUDY_CHECK_DATE,
    fr.STUDY_CHECK_FORM_NUMBER
FROM FIN_ROWS fr
LEFT JOIN MOHECORE.MOHE_QUARTER               q   ON q.QUARTER = fr.MOHE_QUARTER_ID
LEFT JOIN MOHECORE.STUDY_WAFAR_TYPE           wt  ON wt.WAFAR_TYPE_ID = fr.WAFAR_TYPE_ID
LEFT JOIN MOHECORE.STUDY_CURRENCY_IN          cur ON cur.STUDY_CURRENCY_IN_ID = fr.CURRENCY_ID
LEFT JOIN MOHECORE.STUDY_FINANCE_BANK         bk  ON bk.STUDY_FINANCE_BANKE_ID = fr.BANK_ID
LEFT JOIN MOHECORE.STUDY_FINANCE_BANK_BRANCH  bb  ON bb.STUDY_FINANCE_BANK_BRANCH_ID = fr.BANK_BRANCH_ID
LEFT JOIN MOHECORE.STUDY_FIN_RECEIVED_STATUS  rs  ON rs.STUDY_FIN_RECEIVED_STATUS_ID = fr.RECEIVED_STATUS_ID
LEFT JOIN MOHECORE.STUDY_RECEIVED_WHOM_STATUS rws ON rws.STUDY_RECEIVED_WHOM_STATUS_ID = fr.RECEIVED_WHOM_STATUS_ID;
GO
