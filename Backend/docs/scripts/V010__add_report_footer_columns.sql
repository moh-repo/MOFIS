-- Add DB-driven footer text columns to per-report-type settings.
-- Run against MOHE database; idempotent where possible.

IF COL_LENGTH('MOHECORE.REPORT_TYPE_SETTINGS', 'FOOTER_TEXT_AR') IS NULL
BEGIN
    ALTER TABLE MOHECORE.REPORT_TYPE_SETTINGS
        ADD FOOTER_TEXT_AR NVARCHAR(500) NULL;
END;

IF COL_LENGTH('MOHECORE.REPORT_TYPE_SETTINGS', 'FOOTER_TEXT_EN') IS NULL
BEGIN
    ALTER TABLE MOHECORE.REPORT_TYPE_SETTINGS
        ADD FOOTER_TEXT_EN NVARCHAR(500) NULL;
END;
