#!/usr/bin/env python3
"""
Regenerates the official page header / page footer / last-page footer bands in
every JRXML report template.

Why a generator instead of a Jasper subreport: JasperReportService compiles one
self-contained classpath JRXML per report name and has no subreport plumbing,
and a .jrtx style template shares styles but not band layout. Regenerating the
bands textually keeps each template self-contained and diffable, which is how
the rest of this repo maintains them (see update_jrxml_reports.py).

What it produces, sized to each template's own columnWidth (so the historic
"portrait footer geometry on a landscape page" bug cannot come back):

  pageHeader      bilingual masthead - Arabic titles right, ministry logo
                  centre, English titles left - double accent rule, centred
                  report title, meta row (generated date, printed by).
  pageFooter      accent rule, configurable footer text, generated/printed-by,
                  "Page N of M" mirrored for RTL.
  lastPageFooter  same footer plus the signatory blocks, so signatures print
                  once at the end of the report instead of on every page.

Header/footer content stays data-driven: every string comes from a parameter
fed by ReportParamBuilder out of REPORT_TYPE_SETTINGS and SYS_SETTINGS.

Usage:
    python scripts/apply_official_layout.py            # rewrite all templates
    python scripts/apply_official_layout.py --check    # report, change nothing
    python scripts/apply_official_layout.py a.jrxml b.jrxml
"""

from __future__ import annotations

import argparse
import glob
import os
import re
import sys

REPORTS_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "src", "main", "resources", "reports",
)

# Palette. Deliberately the maroon/gold the report templates already used for
# their table headers (#722030 with the #c4922a rule) rather than a new hue, so
# masthead, table and footer read as one document. White background keeps it
# ink-cheap and photocopy-safe, which matters for stamped paper copies.
NAVY = "#3a1422"      # deep maroon, used for masthead and title text
GOLD = "#c4922a"      # accent rule
MUTED = "#7a3040"     # secondary text (dates, page numbers, positions)
BOX_BG = "#fefaf5"    # signatory box fill
BOX_LINE = "#d4a870"

LOGO_W = 60
LOGO_H = 56

# Parameters the generated bands rely on. Any missing from a template are
# declared with an empty/neutral default so it still compiles standalone.
REQUIRED_PARAMS: list[tuple[str, str, str]] = [
    ("IS_RTL", "java.lang.Boolean", "Boolean.TRUE"),
    ("LOGO_IMAGE", "java.io.InputStream", ""),
    ("TITLE_01", "java.lang.String", '""'),
    ("TITLE_01_AR", "java.lang.String", '""'),
    ("TITLE_02_AR", "java.lang.String", '""'),
    ("TITLE_03_AR", "java.lang.String", '""'),
    ("TITLE_01_EN", "java.lang.String", '""'),
    ("TITLE_02_EN", "java.lang.String", '""'),
    ("TITLE_03_EN", "java.lang.String", '""'),
    ("REPORT_TITLE", "java.lang.String", '""'),
    ("PRINTED_BY", "java.lang.String", '""'),
    ("REPORT_DATE", "java.lang.String", '""'),
    ("FOOTER_TEXT", "java.lang.String", '""'),
    ("SIG_COUNT", "java.lang.Integer", "0"),
    ("LBL_GENERATED", "java.lang.String", '"تاريخ الإصدار"'),
    ("LBL_PAGE", "java.lang.String", '"صفحة"'),
    ("LBL_OF", "java.lang.String", '"من"'),
    ("LBL_SIGNATORY", "java.lang.String", '"المفوض بالتوقيع"'),
] + [
    (f"SIG_{kind}_{i}", "java.lang.String", '""')
    for i in range(1, 6) for kind in ("NAME", "POS")
]

MARK_BEGIN = "<!-- OFFICIAL-LAYOUT:BEGIN (generated by scripts/apply_official_layout.py) -->"
MARK_END = "<!-- OFFICIAL-LAYOUT:END -->"

# A template carrying this marker keeps its own header and footer. Used for
# statutory forms whose layout is prescribed by the issuing ministry (the
# payment authorisation voucher is "نموذج رقم ١١ حسابات"), where replacing the
# masthead with the generic one would make the document non-compliant.
MARK_SKIP = "OFFICIAL-LAYOUT:SKIP"


def masthead_geometry(w: int) -> dict[str, int]:
    """Side title stacks + centred logo, proportional to the page width."""
    gap = int(55 * w / 555)
    side_w = (w - LOGO_W - 2 * gap) // 2
    return {
        "side_w": side_w,
        "ar_x": w - side_w,
        "en_x": 0,
        "logo_x": (w - LOGO_W) // 2,
    }


def build_page_header(w: int, has_doc_title: bool = False) -> str:
    g = masthead_geometry(w)
    side_w, ar_x, en_x, logo_x = g["side_w"], g["ar_x"], g["en_x"], g["logo_x"]
    half = w // 2 - 10

    # Arabic side falls back to the single-language TITLE_01 so a template still
    # shows a ministry name when only the legacy parameter is supplied.
    ar1 = ('$P{TITLE_01_AR} != null && !$P{TITLE_01_AR}.isEmpty() '
           '? $P{TITLE_01_AR} : $P{TITLE_01}')
    # Report title prefers the DB report-type name, then the legacy title slots,
    # and finally the template's own LBL_DOC_TITLE where one is declared - so a
    # document is never untitled just because REPORT_TYPE_SETTINGS has no row.
    tail = "$P{TITLE_03}"
    if has_doc_title:
        tail = ('($P{TITLE_03} != null && !$P{TITLE_03}.isEmpty() '
                '? $P{TITLE_03} : $P{LBL_DOC_TITLE})')
    title = ('$P{REPORT_TITLE} != null && !$P{REPORT_TITLE}.isEmpty() ? $P{REPORT_TITLE} '
             ': ($P{TITLE_02} != null && !$P{TITLE_02}.isEmpty() ? $P{TITLE_02} : '
             + tail + ")")

    def stack_field(x, y, width, h, expr, size, bold, rtl):
        direction = ' runDirection="RTL"' if rtl else ""
        b = ' isBold="true"' if bold else ""
        return f"""      <textField>
        <reportElement x="{x}" y="{y}" width="{width}" height="{h}" forecolor="{NAVY}"/>
        <textElement textAlignment="Center" verticalAlignment="Middle"{direction}>
          <font fontName="Cairo" size="{size}"{b}/>
        </textElement>
        <textFieldExpression><![CDATA[{expr}]]></textFieldExpression>
      </textField>
"""

    parts = [f"""  <pageHeader>
    <band height="118" splitType="Stretch">
"""]
    # Arabic stack (right)
    parts.append(stack_field(ar_x, 4, side_w, 16, ar1, 10, True, True))
    parts.append(stack_field(ar_x, 20, side_w, 14, "$P{TITLE_02_AR}", 8, False, True))
    parts.append(stack_field(ar_x, 34, side_w, 13, "$P{TITLE_03_AR}", 8, False, True))
    # Logo (centre)
    parts.append(f"""      <image scaleImage="RetainShape" hAlign="Center" vAlign="Middle" onErrorType="Blank">
        <reportElement x="{logo_x}" y="2" width="{LOGO_W}" height="{LOGO_H}">
          <printWhenExpression><![CDATA[$P{{LOGO_IMAGE}} != null]]></printWhenExpression>
        </reportElement>
        <imageExpression><![CDATA[$P{{LOGO_IMAGE}}]]></imageExpression>
      </image>
""")
    # English stack (left)
    parts.append(stack_field(en_x, 4, side_w, 16, "$P{TITLE_01_EN}", 9, True, False))
    parts.append(stack_field(en_x, 20, side_w, 14, "$P{TITLE_02_EN}", 7, False, False))
    parts.append(stack_field(en_x, 34, side_w, 13, "$P{TITLE_03_EN}", 7, False, False))
    # Double rule + report title + meta row
    parts.append(f"""      <rectangle>
        <reportElement x="0" y="62" width="{w}" height="2" backcolor="{GOLD}" forecolor="{GOLD}"/>
        <graphicElement><pen lineWidth="0.0"/></graphicElement>
      </rectangle>
      <line><reportElement x="0" y="66" width="{w}" height="1" forecolor="{NAVY}"/></line>
      <textField textAdjust="StretchHeight">
        <reportElement x="0" y="72" width="{w}" height="22" forecolor="{NAVY}"/>
        <textElement textAlignment="Center" verticalAlignment="Middle" runDirection="RTL">
          <font fontName="Cairo" size="14" isBold="true"/>
        </textElement>
        <textFieldExpression><![CDATA[{title}]]></textFieldExpression>
      </textField>
      <textField>
        <reportElement x="0" y="98" width="{half}" height="12" forecolor="{MUTED}"/>
        <textElement textAlignment="Left" verticalAlignment="Middle">
          <font fontName="Cairo" size="7"/>
        </textElement>
        <textFieldExpression><![CDATA[$P{{LBL_GENERATED}} + ": " + $P{{REPORT_DATE}}]]></textFieldExpression>
      </textField>
      <textField>
        <reportElement x="{w - half}" y="98" width="{half}" height="12" forecolor="{MUTED}">
          <printWhenExpression><![CDATA[$P{{PRINTED_BY}} != null && !$P{{PRINTED_BY}}.isEmpty()]]></printWhenExpression>
        </reportElement>
        <textElement textAlignment="Right" verticalAlignment="Middle">
          <font fontName="Cairo" size="7"/>
        </textElement>
        <textFieldExpression><![CDATA[$P{{PRINTED_BY}}]]></textFieldExpression>
      </textField>
    </band>
  </pageHeader>
""")
    return "".join(parts)


def _footer_body(w: int, y0: int) -> str:
    """Rule + footer text + generated/printed-by + page numbers, from y0."""
    half = w // 2 - 10

    # "Page N of M" needs two fields: the running page number must evaluate Now
    # while the total only exists at Report time. Their left-to-right order has
    # to flip with the script, or the total lands on the wrong side of "of" and
    # the line reads "1 صفحة 1 من". Both arrangements are emitted and selected by
    # IS_RTL at fill time.
    total_w = 46
    rtl_label_x = w - 150
    rtl_total_x = rtl_label_x - total_w - 4
    ltr_label_x = w - 150
    ltr_total_x = w - total_w

    return f"""      <line><reportElement x="0" y="{y0}" width="{w}" height="1" forecolor="{GOLD}"/></line>
      <textField textAdjust="StretchHeight">
        <reportElement x="0" y="{y0 + 4}" width="{w}" height="12" forecolor="{MUTED}">
          <printWhenExpression><![CDATA[$P{{FOOTER_TEXT}} != null && !$P{{FOOTER_TEXT}}.isEmpty()]]></printWhenExpression>
        </reportElement>
        <textElement textAlignment="Center" verticalAlignment="Middle" runDirection="RTL">
          <font fontName="Cairo" size="7"/>
        </textElement>
        <textFieldExpression><![CDATA[$P{{FOOTER_TEXT}}]]></textFieldExpression>
      </textField>
      <textField>
        <reportElement x="0" y="{y0 + 20}" width="{half}" height="12" forecolor="{MUTED}"/>
        <textElement textAlignment="Left" verticalAlignment="Middle">
          <font fontName="Cairo" size="7"/>
        </textElement>
        <textFieldExpression><![CDATA[$P{{LBL_GENERATED}} + ": " + $P{{REPORT_DATE}} + ($P{{PRINTED_BY}} != null && !$P{{PRINTED_BY}}.isEmpty() ? "  |  " + $P{{PRINTED_BY}} : "")]]></textFieldExpression>
      </textField>
      <textField>
        <reportElement x="{rtl_label_x}" y="{y0 + 20}" width="150" height="12" forecolor="{MUTED}">
          <printWhenExpression><![CDATA[$P{{IS_RTL}}]]></printWhenExpression>
        </reportElement>
        <textElement textAlignment="Right" verticalAlignment="Middle" runDirection="RTL">
          <font fontName="Cairo" size="7"/>
        </textElement>
        <textFieldExpression><![CDATA[$P{{LBL_PAGE}} + " " + $V{{PAGE_NUMBER}}]]></textFieldExpression>
      </textField>
      <textField evaluationTime="Report">
        <reportElement x="{rtl_total_x}" y="{y0 + 20}" width="{total_w}" height="12" forecolor="{MUTED}">
          <printWhenExpression><![CDATA[$P{{IS_RTL}}]]></printWhenExpression>
        </reportElement>
        <textElement textAlignment="Right" verticalAlignment="Middle" runDirection="RTL">
          <font fontName="Cairo" size="7"/>
        </textElement>
        <textFieldExpression><![CDATA[$P{{LBL_OF}} + " " + $V{{PAGE_NUMBER}}]]></textFieldExpression>
      </textField>
      <textField>
        <reportElement x="{ltr_label_x}" y="{y0 + 20}" width="{ltr_total_x - ltr_label_x - 2}" height="12" forecolor="{MUTED}">
          <printWhenExpression><![CDATA[!$P{{IS_RTL}}]]></printWhenExpression>
        </reportElement>
        <textElement textAlignment="Right" verticalAlignment="Middle">
          <font fontName="Cairo" size="7"/>
        </textElement>
        <textFieldExpression><![CDATA[$P{{LBL_PAGE}} + " " + $V{{PAGE_NUMBER}} + " " + $P{{LBL_OF}}]]></textFieldExpression>
      </textField>
      <textField evaluationTime="Report">
        <reportElement x="{ltr_total_x}" y="{y0 + 20}" width="{total_w}" height="12" forecolor="{MUTED}">
          <printWhenExpression><![CDATA[!$P{{IS_RTL}}]]></printWhenExpression>
        </reportElement>
        <textElement textAlignment="Left" verticalAlignment="Middle">
          <font fontName="Cairo" size="7"/>
        </textElement>
        <textFieldExpression><![CDATA[" " + $V{{PAGE_NUMBER}}]]></textFieldExpression>
      </textField>
"""


def build_page_footer(w: int) -> str:
    return f"""  <pageFooter>
    <band height="42" splitType="Stretch">
{_footer_body(w, 0)}    </band>
  </pageFooter>
"""


def build_last_page_footer(w: int) -> str:
    """Signatory boxes (RTL: signatory 1 rightmost) above the normal footer."""
    box_w = w // 5
    sig_h = 70
    parts = [f"""  <lastPageFooter>
    <band height="{sig_h + 48}" splitType="Stretch">
"""]
    for i in range(1, 6):
        x = w - i * box_w
        cond = f"$P{{SIG_COUNT}} >= {i}"
        parts.append(f"""      <rectangle>
        <reportElement x="{x}" y="2" width="{box_w}" height="{sig_h}" backcolor="{BOX_BG}" forecolor="{BOX_LINE}">
          <printWhenExpression><![CDATA[{cond}]]></printWhenExpression>
        </reportElement>
        <graphicElement><pen lineWidth="0.5"/></graphicElement>
      </rectangle>
      <textField>
        <reportElement x="{x}" y="5" width="{box_w}" height="11" forecolor="{MUTED}">
          <printWhenExpression><![CDATA[{cond}]]></printWhenExpression>
        </reportElement>
        <textElement textAlignment="Center" verticalAlignment="Middle" runDirection="RTL">
          <font fontName="Cairo" size="6"/>
        </textElement>
        <textFieldExpression><![CDATA[$P{{LBL_SIGNATORY}}]]></textFieldExpression>
      </textField>
      <textField>
        <reportElement x="{x}" y="18" width="{box_w}" height="12" forecolor="{NAVY}">
          <printWhenExpression><![CDATA[{cond}]]></printWhenExpression>
        </reportElement>
        <textElement textAlignment="Center" verticalAlignment="Middle" runDirection="RTL">
          <font fontName="Cairo" size="7" isBold="true"/>
        </textElement>
        <textFieldExpression><![CDATA[$P{{SIG_NAME_{i}}}]]></textFieldExpression>
      </textField>
      <line>
        <reportElement x="{x + 10}" y="{sig_h - 22}" width="{box_w - 20}" height="1" forecolor="{GOLD}">
          <printWhenExpression><![CDATA[{cond}]]></printWhenExpression>
        </reportElement>
      </line>
      <textField>
        <reportElement x="{x}" y="{sig_h - 18}" width="{box_w}" height="11" forecolor="{MUTED}">
          <printWhenExpression><![CDATA[{cond}]]></printWhenExpression>
        </reportElement>
        <textElement textAlignment="Center" verticalAlignment="Middle" runDirection="RTL">
          <font fontName="Cairo" size="6"/>
        </textElement>
        <textFieldExpression><![CDATA[$P{{SIG_POS_{i}}}]]></textFieldExpression>
      </textField>
""")
    parts.append(_footer_body(w, sig_h + 6))
    parts.append("""    </band>
  </lastPageFooter>
""")
    return "".join(parts)


def ensure_params(src: str) -> tuple[str, list[str]]:
    """Declare any generator-required parameter the template is missing."""
    added = []
    lines = []
    for name, cls, default in REQUIRED_PARAMS:
        if re.search(rf'<parameter\s+name="{re.escape(name)}"', src):
            continue
        added.append(name)
        if default:
            lines.append(
                f'  <parameter name="{name}" class="{cls}">'
                f"<defaultValueExpression><![CDATA[{default}]]></defaultValueExpression></parameter>"
            )
        else:
            lines.append(f'  <parameter name="{name}" class="{cls}"/>')
    if not lines:
        return src, added

    block = "\n".join(lines) + "\n"
    # After the last existing <parameter>, else before the first <field>/band.
    last_param = None
    for m in re.finditer(r"[ \t]*<parameter\b.*?(?:/>|</parameter>)\n", src, re.S):
        last_param = m
    if last_param:
        return src[: last_param.end()] + block + src[last_param.end():], added
    anchor = re.search(r"[ \t]*<(field|variable|group|background|title|pageHeader)\b", src)
    if not anchor:
        raise SystemExit("cannot find an insertion point for parameters")
    return src[: anchor.start()] + block + src[anchor.start():], added


# Zero literal per variable class, for seeding empty-data totals.
ZERO_FOR_CLASS = {
    "java.lang.Integer": "0",
    "java.lang.Long": "0L",
    "java.lang.Double": "0.0",
    "java.lang.Float": "0.0f",
    "java.math.BigDecimal": "java.math.BigDecimal.ZERO",
}


def seed_total_variables(src: str) -> tuple[str, int]:
    """
    Give Count/Sum variables an explicit zero initial value.

    Jasper leaves such a variable null when the dataset is empty, so a summary
    band prints "Total Records: null" on an official document instead of 0.
    """
    fixed = 0

    def repl(m: re.Match) -> str:
        nonlocal fixed
        block = m.group(0)
        if "<initialValueExpression>" in block:
            return block
        cls = re.search(r'class="([^"]+)"', block)
        calc = re.search(r'calculation="(Count|Sum)"', block)
        if not cls or not calc:
            return block
        zero = ZERO_FOR_CLASS.get(cls.group(1))
        if zero is None:
            return block
        fixed += 1
        indent = re.match(r"[ \t]*", block).group(0)
        return block.replace(
            "</variable>",
            f"{indent}  <initialValueExpression><![CDATA[{zero}]]></initialValueExpression>\n"
            f"{indent}</variable>",
        )

    src = re.sub(r"[ \t]*<variable\b[^>]*>.*?</variable>\n", repl, src, flags=re.S)
    return src, fixed


def strip_band(src: str, tag: str) -> str:
    """Remove a band element plus any stray banner comments left before it."""
    src = re.sub(rf"[ \t]*<{tag}>.*?</{tag}>\n", "", src, flags=re.S)
    # update_jrxml_reports.py left duplicated "<!-- PAGE FOOTER -->" markers behind
    src = re.sub(r"[ \t]*<!--\s*(PAGE FOOTER|PAGE HEADER|═+[^>]*?)\s*-->\n", "", src)
    return src


def rewrite(path: str) -> tuple[bool, str]:
    src = open(path, encoding="utf-8").read()
    original = src

    if MARK_SKIP in src:
        return False, "opted out (prescribed statutory layout)"

    m = re.search(r'columnWidth="(\d+)"', src)
    if not m:
        return False, "no columnWidth"
    w = int(m.group(1))

    # Drop a previous generation of these bands before regenerating.
    src = re.sub(re.escape(MARK_BEGIN) + r".*?" + re.escape(MARK_END) + r"\n", "", src, flags=re.S)
    for tag in ("pageHeader", "pageFooter", "lastPageFooter"):
        src = strip_band(src, tag)

    src, added = ensure_params(src)
    src, seeded = seed_total_variables(src)

    has_doc_title = bool(re.search(r'<parameter\s+name="LBL_DOC_TITLE"', src))
    bands = (
        MARK_BEGIN + "\n"
        + build_page_header(w, has_doc_title)
        + build_page_footer(w)
        + build_last_page_footer(w)
        + MARK_END + "\n"
    )

    # Jasper's element order is pageHeader, columnHeader, detail, columnFooter,
    # pageFooter, lastPageFooter, summary. The engine's parser is lenient (see
    # NonValidatingSaxParserFactory) so emitting the three bands together just
    # before </jasperReport> parses fine and keeps the generated block in one
    # contiguous, reviewable place.
    close = src.rindex("</jasperReport>")
    src = src[:close] + bands + src[close:]

    if src == original:
        return False, "unchanged"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)
    note = f"width={w}"
    if added:
        note += f", +{len(added)} params"
    if seeded:
        note += f", {seeded} totals seeded"
    return True, note


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("templates", nargs="*", help="template files (default: all in reports/)")
    ap.add_argument("--check", action="store_true", help="report only, write nothing")
    args = ap.parse_args()

    files = args.templates or sorted(glob.glob(os.path.join(REPORTS_DIR, "*.jrxml")))
    if not files:
        print("no templates found", file=sys.stderr)
        return 1

    changed = 0
    for path in files:
        name = os.path.basename(path)
        if args.check:
            src = open(path, encoding="utf-8").read()
            state = "generated" if MARK_BEGIN in src else "legacy"
            w = re.search(r'columnWidth="(\d+)"', src)
            print(f"{name:42s} {state:9s} width={w.group(1) if w else '?'}")
            continue
        ok, note = rewrite(path)
        changed += ok
        print(f"{'rewrote' if ok else 'skipped':8s} {name:42s} {note}")

    if not args.check:
        print(f"\n{changed}/{len(files)} templates rewritten")
    return 0


if __name__ == "__main__":
    sys.exit(main())
