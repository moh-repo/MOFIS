"""Generate V064 (the revenue chart of accounts) from the ministry's workbook.

The ministry's monthly revenue statement form, `مفردات الموارد.xls`, carries the
economic classification of revenue down its first five columns:

    description | الباب | الفصل | البند | النوع

exactly one of the four code columns is filled on a classification row, and
the depth of that column is the level. This script reads one sheet, rebuilds
the tree, validates it, and writes an idempotent T-SQL migration that inserts
the accounts under the ECONOMIC segment for every open fiscal year.

Why a generator and not a hand-written script: the chart is a controlled
document. Every code and name in V064 must be traceable to the sheet, and if
the ministry issues a corrected sheet the script is re-run, not re-typed.

Usage (from Backend/):
    python scripts/coa_from_workbook.py "docs/reference/مفردات الموارد.xls" \
        --sheet 2 --out docs/scripts/V064__chart_of_accounts_revenue.sql

The workbook is encrypted with Excel's default key ("VelvetSweatshop" — sheet
protection, not a password); `msoffcrypto-tool` opens it. Needs `xlrd` and
`msoffcrypto-tool` (pip install xlrd msoffcrypto-tool).
"""
from __future__ import annotations

import argparse
import collections
import io
import re
import sys
from pathlib import Path

import msoffcrypto
import xlrd

# Widths read from the manual itself (largest code at each level: 5, 7, 7, 23).
LEVELS = [
    (1, "باب", "Chapter", 1),
    (2, "فصل", "Section", 1),
    (3, "بند", "Item", 1),
    (4, "نوع", "Type", 2),
]
NOTE_PREFIXES = ("جملة", "إجمالي", "اجمالي", "بيان", "المستبعد")


def norm_code(v):
    if v in ("", None):
        return None
    if isinstance(v, float):
        return int(v) if v == int(v) else None
    s = str(v).strip()
    return int(s) if re.fullmatch(r"\d+", s) else None


def clean_name(s: str) -> str:
    return re.sub(r"\s+", " ", str(s).replace("ـ", "")).strip()


def open_workbook(path: Path) -> xlrd.book.Book:
    raw = path.read_bytes()
    office = msoffcrypto.OfficeFile(io.BytesIO(raw))
    if office.is_encrypted():
        office.load_key(password="VelvetSweatshop")
        out = io.BytesIO()
        office.decrypt(out)
        raw = out.getvalue()
    return xlrd.open_workbook(file_contents=raw)


def read_tree(sheet):
    """Returns [(row, level, path_tuple, name)] in sheet order."""
    stack: dict[int, int] = {}
    nodes = []
    for r in range(sheet.nrows):
        name = clean_name(sheet.cell_value(r, 0))
        codes = [norm_code(sheet.cell_value(r, c)) for c in range(1, 5)]
        filled = [i for i, x in enumerate(codes) if x is not None]
        if len(filled) != 1:
            continue
        level = filled[0] + 1
        code = codes[filled[0]]
        if not name or name.startswith(NOTE_PREFIXES):
            sys.exit(f"row {r}: code {code} at level {level} without a usable name: {name!r}")
        for deeper in [l for l in list(stack) if l >= level]:
            del stack[deeper]
        if any(l not in stack for l in range(1, level)):
            sys.exit(f"row {r}: level-{level} code {code} has no parent above it")
        stack[level] = code
        nodes.append((r, level, tuple(stack[l] for l in range(1, level + 1)), name))
    return nodes


def validate(nodes):
    dups = [p for p, c in collections.Counter(p for _, _, p, _ in nodes).items() if c > 1]
    if dups:
        sys.exit("duplicate code paths (a sheet with typos?): " + ", ".join(".".join(map(str, p)) for p in dups))
    widths = {lvl: w for lvl, _, _, w in LEVELS}
    for _, level, path, _ in nodes:
        if len(str(path[-1])) > widths[level]:
            sys.exit(f"code {path[-1]} at level {level} is wider than the manual's width {widths[level]}")
    paths = {p for _, _, p, _ in nodes}
    leaves = {p for p in paths if not any(q[: len(p)] == p and len(q) > len(p) for q in paths)}
    return leaves


def code_str(level: int, code: int) -> str:
    width = {lvl: w for lvl, _, _, w in LEVELS}[level]
    return str(code).zfill(width)


def full_code(path) -> str:
    return "".join(code_str(i + 1, c) for i, c in enumerate(path))


def sql_str(s: str) -> str:
    return "N'" + s.replace("'", "''") + "'"


def emit(nodes, leaves, source_name: str, sheet_name: str) -> str:
    per_level = collections.Counter(l for _, l, _, _ in nodes)
    out = []
    w = out.append
    w(f"""/*
    V064 — the revenue chart of accounts (مفردات الموارد), from the ministry's own form.

    GENERATED by Backend/scripts/coa_from_workbook.py from
        {source_name}   (sheet "{sheet_name}")
    Do not edit by hand: re-run the generator on a corrected sheet instead.

    What it loads
    -------------
    The economic classification of revenue — الباب / الفصل / البند / النوع —
    as printed down the left of the monthly revenue statement:
        {per_level.get(1,0)} أبواب, {per_level.get(2,0)} فصول, {per_level.get(3,0)} بنود, {per_level.get(4,0)} أنواع
        = {len(nodes)} accounts per fiscal year, {len(leaves)} of them leaves (postable).
    Loaded under the ECONOMIC segment for EVERY fiscal year that is OPEN, because
    the chart is versioned per year (V041) and the open years share one Regulation.

    Decisions (see docs/chart-of-accounts-revenue-load.md)
    -------------------------------------------------------
      * The 2019 sheets are the source; sheet 1 (2026) has three code typos.
      * Levels 1–4 of the economic segment are renamed to the form's names
        (باب / فصل / بند / نوع) and given the widths read from the manual
        (1 / 1 / 1 / 2). Level 5 (حساب) keeps no width.
      * Every account is REVENUE / credit-normal: the form calls all five
        chapters موارد. IS_BUDGETARY = 1. Country NULL (national chart).
      * Type codes are zero-padded to two digits, so FULL_CODE is unambiguous.

    Idempotent: an account whose (segment, year, FULL_CODE) exists is left
    alone — names are never overwritten by a re-run. The level rename only
    happens while the levels still carry V041's seeded names.
    The V041 trigger validates parent, full code, width and postability.
    Needs QUOTED_IDENTIFIER ON (sqlcmd -I) and UTF-8 (-f 65001).
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;
SET QUOTED_IDENTIFIER ON;
GO

DECLARE @seg int = (SELECT SEGMENT_ID FROM FINCORE.COA_SEGMENT WHERE SEGMENT_CODE = 'ECONOMIC');
IF @seg IS NULL THROW 50064, 'V064: the ECONOMIC segment (V041) is missing.', 1;

/* ── 1. Level names and widths, only while they are still V041's seed ──────── */
IF EXISTS (SELECT 1 FROM FINCORE.COA_LEVEL WHERE SEGMENT_ID = @seg AND LEVEL_NO = 2 AND NAME_AR = N'بند' AND CODE_LENGTH IS NULL)
BEGIN""")
    for lvl, ar, en, width in LEVELS:
        w(f"    UPDATE FINCORE.COA_LEVEL SET NAME_AR = {sql_str(ar)}, NAME_EN = N'{en}', CODE_LENGTH = {width} WHERE SEGMENT_ID = @seg AND LEVEL_NO = {lvl};")
    w("""    PRINT 'V064: economic levels renamed to the form''s names with widths 1/1/1/2';
END
ELSE PRINT 'V064: economic levels already named/sized — left alone';
GO

/* ── 2. The accounts, per open fiscal year ─────────────────────────────────── */
DECLARE @seg int = (SELECT SEGMENT_ID FROM FINCORE.COA_SEGMENT WHERE SEGMENT_CODE = 'ECONOMIC');
DECLARE @chart TABLE (ord int IDENTITY(1,1), level_no tinyint, code nvarchar(20), full_code nvarchar(80),
                      parent_full nvarchar(80) NULL, name_ar nvarchar(300), postable bit);
INSERT INTO @chart (level_no, code, full_code, parent_full, name_ar, postable) VALUES""")
    rows = []
    for _, level, path, name in nodes:
        parent = "NULL" if level == 1 else sql_str(full_code(path[:-1]))
        rows.append(f"    ({level}, N'{code_str(level, path[-1])}', N'{full_code(path)}', {parent}, {sql_str(name)}, {1 if path in leaves else 0})")
    w(",\n".join(rows) + ";")
    w("""
DECLARE @year int, @inserted int, @skipped int;
DECLARE years CURSOR LOCAL FAST_FORWARD FOR
    SELECT FISCAL_YEAR_ID FROM FINCORE.FISCAL_YEAR WHERE STATUS = 'OPEN' ORDER BY YEAR_NO;
OPEN years;
FETCH NEXT FROM years INTO @year;
WHILE @@FETCH_STATUS = 0
BEGIN
    SET @inserted = 0; SET @skipped = 0;
    BEGIN TRAN;
    DECLARE @ord int = 1, @max int = (SELECT MAX(ord) FROM @chart);
    WHILE @ord <= @max
    BEGIN
        DECLARE @lvl tinyint, @code nvarchar(20), @full nvarchar(80), @pfull nvarchar(80), @name nvarchar(300), @post bit;
        SELECT @lvl = level_no, @code = code, @full = full_code, @pfull = parent_full, @name = name_ar, @post = postable
          FROM @chart WHERE ord = @ord;
        IF EXISTS (SELECT 1 FROM FINCORE.COA_ACCOUNT WHERE SEGMENT_ID = @seg AND FISCAL_YEAR_ID = @year AND FULL_CODE = @full)
            SET @skipped += 1;
        ELSE
        BEGIN
            DECLARE @parent int = NULL;
            IF @pfull IS NOT NULL
            BEGIN
                SET @parent = (SELECT ACCOUNT_ID FROM FINCORE.COA_ACCOUNT WHERE SEGMENT_ID = @seg AND FISCAL_YEAR_ID = @year AND FULL_CODE = @pfull);
                IF @parent IS NULL THROW 50065, 'V064: parent missing for a chart row — generator ordering broken.', 1;
            END
            INSERT INTO FINCORE.COA_ACCOUNT
                (SEGMENT_ID, LEVEL_NO, PARENT_ACCOUNT_ID, CODE, FULL_CODE, NAME_AR, NAME_EN,
                 ACCOUNT_NATURE, NORMAL_BALANCE, IS_POSTABLE, IS_BUDGETARY, FISCAL_YEAR_ID, STUDY_COUNTRY_IN_ID)
            VALUES (@seg, @lvl, @parent, @code, @full, @name, NULL, 'REVENUE', 'C', @post, 1, @year, NULL);
            SET @inserted += 1;
        END
        SET @ord += 1;
    END
    COMMIT;
    PRINT 'V064: fiscal year id ' + CAST(@year AS varchar(10)) + ' — inserted ' + CAST(@inserted AS varchar(10)) + ', already present ' + CAST(@skipped AS varchar(10));
    FETCH NEXT FROM years INTO @year;
END
CLOSE years; DEALLOCATE years;
GO

/* ── Verification ─────────────────────────────────────────────────────────── */
SELECT fy.YEAR_NO, a.LEVEL_NO, COUNT(*) AS accounts, SUM(CASE WHEN a.IS_POSTABLE = 1 THEN 1 ELSE 0 END) AS postable
  FROM FINCORE.COA_ACCOUNT a JOIN FINCORE.FISCAL_YEAR fy ON fy.FISCAL_YEAR_ID = a.FISCAL_YEAR_ID
  JOIN FINCORE.COA_SEGMENT s ON s.SEGMENT_ID = a.SEGMENT_ID AND s.SEGMENT_CODE = 'ECONOMIC'
 GROUP BY fy.YEAR_NO, a.LEVEL_NO ORDER BY 1, 2;
GO
""")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("workbook")
    ap.add_argument("--sheet", default="2", help="sheet name to read (default: 2, the first 2019 sheet)")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    wb = open_workbook(Path(args.workbook))
    sheet = wb.sheet_by_name(args.sheet)
    nodes = read_tree(sheet)
    leaves = validate(nodes)
    sql = emit(nodes, leaves, Path(args.workbook).name, args.sheet)
    Path(args.out).write_text(sql, encoding="utf-8", newline="\n")
    per_level = collections.Counter(l for _, l, _, _ in nodes)
    print(f"{args.out}: {len(nodes)} accounts ({dict(sorted(per_level.items()))}), {len(leaves)} postable leaves")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
