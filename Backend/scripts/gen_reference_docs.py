"""Regenerate the generated parts of docs/ENVIRONMENT.md and docs/MIGRATION_RUNBOOK.md.

    python scripts/gen_reference_docs.py           # rewrite both files
    python scripts/gen_reference_docs.py --check   # exit 1 when either is stale

ENVIRONMENT.md lists every ${VARIABLE} the application*.properties files read,
with the property it feeds and the default each profile gives it.
MIGRATION_RUNBOOK.md keeps its hand-written text above the GENERATED marker; the
table of scripts below the marker is rebuilt from docs/scripts/V*.sql (version,
file, and the title line of each script's header comment).

Needs nothing but the repository: no database, no third-party packages.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
RESOURCES = BACKEND / "src" / "main" / "resources"
SCRIPTS = BACKEND / "docs" / "scripts"
ENV_DOC = BACKEND / "docs" / "ENVIRONMENT.md"
RUNBOOK = BACKEND / "docs" / "MIGRATION_RUNBOOK.md"
MARKER = "<!-- GENERATED BELOW by scripts/gen_reference_docs.py; edit above this line only -->"

PROFILES = [("application.properties", "base"),
            ("application-dev.properties", "dev"),
            ("application-prod.properties", "prod")]
PLACEHOLDER = re.compile(r"\$\{([A-Z][A-Z0-9_]*)(?::([^}]*))?\}")
# A default that looks like a credential or key is shown as "(set, dev only)".
SECRETISH = re.compile(r"(PASSWORD|SECRET|_KEY$|KEY_PREVIOUS|ENCRYPTION)", re.I)
BASELINE_VERSION = 96


def read_properties(path: Path):
    """(key, value) pairs; handles backslash line continuations."""
    lines, buf = [], ""
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not buf and (not line or line.startswith(("#", "!"))):
            continue
        if line.endswith("\\"):
            buf += line[:-1]
            continue
        line, buf = buf + line, ""
        if "=" in line:
            key, value = line.split("=", 1)
            lines.append((key.strip(), value.strip()))
    return lines


def environment_doc() -> str:
    rows: dict[str, dict] = {}
    for filename, profile in PROFILES:
        for key, value in read_properties(RESOURCES / filename):
            for m in PLACEHOLDER.finditer(value):
                var, default = m.group(1), m.group(2)
                entry = rows.setdefault(var, {"properties": [], "defaults": {}})
                if key not in entry["properties"]:
                    entry["properties"].append(key)
                entry["defaults"][profile] = default

    def show(var, profile, entry):
        if profile not in entry["defaults"]:
            return ""
        default = entry["defaults"][profile]
        if default is None:
            return "**required**"
        if default == "":
            return "(empty)"
        if SECRETISH.search(var):
            return "(set, dev only)" if profile == "dev" else "(set)"
        return f"`{default}`"

    out = [
        "# Environment variables",
        "",
        "Generated by `Backend/scripts/gen_reference_docs.py` from the `${VARIABLE}` placeholders in",
        "`src/main/resources/application*.properties`; do not edit by hand.",
        "",
        "- **base** is `application.properties`, which every profile reads; **dev** and **prod** override it.",
        "- **required** means the profile has no fallback: startup fails when the variable is unset.",
        "- Credential defaults are not printed. The dev ones exist so a local `-Dspring-boot.run.profiles=dev`",
        "  run starts; the prod profile has none.",
        "- Every Spring property can also be set directly (e.g. `SPRING_FLYWAY_BASELINEVERSION`); only the",
        "  variables the files name explicitly are listed.",
        "- The service must run with a UTF-8 locale (`LANG=C.UTF-8`): file names with Arabic characters fail",
        "  otherwise (ENV-01). This is an OS setting, not a property.",
        "",
        "| Variable | Property | base | dev | prod |",
        "|---|---|---|---|---|",
    ]
    for var in sorted(rows):
        entry = rows[var]
        props = "<br>".join(f"`{p}`" for p in entry["properties"])
        out.append(f"| `{var}` | {props} | {show(var, 'base', entry)} | "
                   f"{show(var, 'dev', entry)} | {show(var, 'prod', entry)} |")
    out.append("")
    return "\n".join(out)


def script_title(path: Path) -> str:
    """The first meaningful line of the header comment, minus the 'Vnnn -' prefix."""
    text = path.read_text(encoding="utf-8-sig", errors="replace")
    for raw in text.splitlines()[:25]:
        line = raw.strip().lstrip("/*-").strip()
        if not line or line.startswith(("=", "*")):
            continue
        line = re.sub(r"^V\d+\s*[-—–:]\s*", "", line)
        return line.replace("|", "\\|")[:160]
    return ""


def migration_table() -> str:
    out = [MARKER, "", "## Scripts", "",
           "| Version | Applied by | File | Title |", "|---|---|---|---|"]
    for path in sorted(SCRIPTS.glob("V*.sql"), key=lambda p: int(re.match(r"V(\d+)", p.name).group(1))):
        version = int(re.match(r"V(\d+)", path.name).group(1))
        who = "hand" if version <= BASELINE_VERSION else "Flyway"
        out.append(f"| {version:03d} | {who} | `{path.name}` | {script_title(path)} |")
    out.append("")
    return "\n".join(out)


def runbook_doc() -> str:
    head = RUNBOOK.read_text(encoding="utf-8").split(MARKER)[0].rstrip() + "\n\n"
    return head + migration_table()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when a generated file is out of date")
    args = ap.parse_args()
    stale = []
    for target, content in ((ENV_DOC, environment_doc()), (RUNBOOK, runbook_doc())):
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != content:
            stale.append(target)
            if not args.check:
                target.write_text(content, encoding="utf-8")
    if args.check and stale:
        for target in stale:
            print(f"stale: {target.relative_to(BACKEND)} (run python scripts/gen_reference_docs.py)")
        return 1
    for target in stale:
        print(f"wrote {target.relative_to(BACKEND)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
