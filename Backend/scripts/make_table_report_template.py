#!/usr/bin/env python3
"""Generate the body of a landscape table report template.

Every tabular report in this repo has the same skeleton: a style, a parameter
block, field declarations, a coloured column header, a striped detail band and a
totals summary. Only the columns differ. Writing that by hand six times invites
the two mistakes it is easy to make and hard to see:

  * column x-offsets that do not add up to columnWidth, so the last cell is
    clipped or a gap opens on one edge; and
  * a width sequence that is not a palindrome, which breaks the RTL mirror —
    every cell picks its field from IS_RTL, and that only lines up when slot N
    and slot (count+1-N) are the same width.

Both are checked here and refused rather than rendered.

The masthead, page footer and signatory bands are NOT produced here. Run
apply_official_layout.py afterwards; it owns those and sizes them to the
template's own columnWidth.

Usage:
    python scripts/make_table_report_template.py <spec.json>

Spec shape:
    {
      "name": "accounting-position",
      "accent": "#1d5b4c",            # column header background
      "columns": [
        {"width": 96, "label": "COL_ATTACHE", "field": "studyCountryName"},
        ...
      ],
      "extraParams":  [{"name": "FISCAL_YEAR_NAME", "class": "java.lang.String", "default": "\\"\\""}],
      "fields":       [{"name": "available", "class": "java.math.BigDecimal"}],
      "summaryLines": ["$P{LBL_TOTAL_RECORDS} + \\": \\" + $V{ROW_NUMBER}"]
    }

`columns` order is the LEFT-TO-RIGHT (English) order; the Arabic mirror is
derived, so it can never drift from it.
"""

from __future__ import annotations

import json
import os
import sys

REPORTS_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "src", "main", "resources", "reports")

PAGE_COLUMN_WIDTH = 802


def darker(hex_colour: str) -> str:
    """A slightly darker shade of the accent, for the column separators."""
    r, g, b = (int(hex_colour[i:i + 2], 16) for i in (1, 3, 5))
    return "#%02x%02x%02x" % (int(r * 0.6), int(g * 0.6), int(b * 0.6))


def cell_expression(field: dict) -> str:
    name = field["field"]
    cls = field.get("class", "java.lang.String")
    if cls.endswith("LocalDateTime"):
        return ('($F{%s} != null ? String.valueOf($F{%s}).replace("T", " ") : "")' % (name, name))
    if cls == "java.lang.String":
        return '($F{%s} != null ? $F{%s} : "")' % (name, name)
    return '($F{%s} != null ? String.valueOf($F{%s}) : "")' % (name, name)


def build(spec: dict) -> str:
    cols = spec["columns"]
    widths = [c["width"] for c in cols]

    total = sum(widths)
    if total != PAGE_COLUMN_WIDTH:
        raise SystemExit(
            f"column widths sum to {total}, not {PAGE_COLUMN_WIDTH} — "
            "the last cell would be clipped or a gap would open")
    if widths != widths[::-1]:
        raise SystemExit(
            "column widths are not a palindrome, so the RTL mirror would not line up: "
            f"{widths}")

    accent = spec.get("accent", "#34495e")
    line = darker(accent)
    stripe = spec.get("stripe", "#f4f6f8")
    rule = spec.get("rule", "#d6dde3")

    xs, x = [], 0
    for w in widths:
        xs.append(x)
        x += w

    mirrored = list(reversed(cols))

    out = []
    add = out.append

    add('<?xml version="1.0" encoding="UTF-8"?>')
    add('<!DOCTYPE jasperReport PUBLIC "-//JasperReports//DTD Report Design//EN"')
    add('  "http://jasperreports.sourceforge.net/dtds/jasperreport.dtd">')
    add('<jasperReport xmlns="http://jasperreports.sourceforge.net/jasperreports"')
    add('  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"')
    add('  xsi:schemaLocation="http://jasperreports.sourceforge.net/jasperreports')
    add('    http://jasperreports.sourceforge.net/xsd/jasperreport.xsd"')
    add(f'  name="{spec["name"]}"')
    add('  pageWidth="842" pageHeight="595"')
    add('  orientation="Landscape"')
    add('')
    add(f'  columnWidth="{PAGE_COLUMN_WIDTH}" leftMargin="20" rightMargin="20"')
    add('  topMargin="10" bottomMargin="15"')
    add('  whenNoDataType="AllSectionsNoDetail">')
    add('')
    add('  <!-- Generated by scripts/make_table_report_template.py; edit the spec, not this file. -->')
    add('  <style name="defaultStyle" isDefault="true" fontName="Cairo" fontSize="9"/>')
    add('')
    add(f'  <!-- Column widths are a palindrome ({",".join(str(w) for w in widths)}),')
    add('       so the Arabic layout is the exact mirror of the English one. -->')
    add('')
    add('  <!-- PARAMETERS -->')
    for name, default in (
            ("IS_RTL", "Boolean.TRUE"),
    ):
        add(f'  <parameter name="{name}" class="java.lang.Boolean"><defaultValueExpression><![CDATA[{default}]]></defaultValueExpression></parameter>')
    add('  <parameter name="LANG" class="java.lang.String"><defaultValueExpression><![CDATA["ar"]]></defaultValueExpression></parameter>')
    add('  <parameter name="LOGO_IMAGE" class="java.io.InputStream"/>')
    for name in ("REPORT_DATE", "FOOTER_TEXT", "REPORT_TITLE", "PRINTED_BY",
                 "TITLE_02", "TITLE_03", "TITLE_04", "TITLE_05"):
        add(f'  <parameter name="{name}" class="java.lang.String"><defaultValueExpression><![CDATA[""]]></defaultValueExpression></parameter>')
    add('  <parameter name="LBL_TOTAL_RECORDS" class="java.lang.String"><defaultValueExpression><![CDATA["Total Records"]]></defaultValueExpression></parameter>')
    add('  <parameter name="LBL_NO_DATA" class="java.lang.String"><defaultValueExpression><![CDATA["No data"]]></defaultValueExpression></parameter>')
    for c in cols:
        add(f'  <parameter name="{c["label"]}" class="java.lang.String"><defaultValueExpression><![CDATA["{c.get("fallback", c["label"])}"]]></defaultValueExpression></parameter>')
    for p in spec.get("extraParams", []):
        add(f'  <parameter name="{p["name"]}" class="{p.get("class", "java.lang.String")}"><defaultValueExpression><![CDATA[{p.get("default", chr(34) + chr(34))}]]></defaultValueExpression></parameter>')
    add('')
    add('  <!-- FIELDS -->')
    seen = set()
    for c in cols:
        if c["field"] in seen:
            continue
        seen.add(c["field"])
        add(f'  <field name="{c["field"]}" class="{c.get("class", "java.lang.String")}"/>')
    for f in spec.get("fields", []):
        if f["name"] in seen:
            continue
        seen.add(f["name"])
        add(f'  <field name="{f["name"]}" class="{f.get("class", "java.lang.String")}"/>')
    add('')
    add('  <!-- VARIABLES -->')
    add('  <variable name="ROW_NUMBER" class="java.lang.Integer" calculation="Count">')
    add(f'    <variableExpression><![CDATA[$F{{{cols[0]["field"]}}}]]></variableExpression>')
    add('    <initialValueExpression><![CDATA[0]]></initialValueExpression>')
    add('  </variable>')
    add('')

    if spec.get("bannerParam"):
        add('  <title>')
        add('    <band height="20" splitType="Stretch">')
        add('      <textField>')
        add('        <reportElement x="0" y="2" width="802" height="16" forecolor="#2c3e50"/>')
        add('        <textElement textAlignment="Center" verticalAlignment="Middle"><font fontName="Cairo" size="9" isBold="true"/></textElement>')
        add(f'        <textFieldExpression><![CDATA[$P{{{spec["bannerParam"]}}} == null ? "" : $P{{{spec["bannerParam"]}}}]]></textFieldExpression>')
        add('      </textField>')
        add('    </band>')
        add('  </title>')
        add('')

    # COLUMN HEADER
    add('  <columnHeader>')
    add('    <band height="22" splitType="Stretch">')
    add('      <rectangle>')
    add(f'        <reportElement x="0" y="0" width="802" height="22" backcolor="{accent}" forecolor="{accent}"/>')
    add('        <graphicElement><pen lineWidth="0.0"/></graphicElement>')
    add('      </rectangle>')
    add('      <line><reportElement x="0" y="21" width="802" height="1" forecolor="#c4922a"/></line>')
    for i, (x0, w) in enumerate(zip(xs, widths)):
        add('      <textField textAdjust="StretchHeight">')
        add(f'        <reportElement x="{x0}" y="0" width="{w}" height="22" forecolor="#FFFFFF"/>')
        add('        <textElement textAlignment="Center" verticalAlignment="Middle"><font fontName="Cairo" size="8" isBold="true"/></textElement>')
        add(f'        <textFieldExpression><![CDATA[$P{{IS_RTL}} ? $P{{{mirrored[i]["label"]}}} : $P{{{cols[i]["label"]}}}]]></textFieldExpression>')
        add('      </textField>')
    for x0 in xs[1:]:
        add(f'      <line><reportElement x="{x0}" y="0" width="1" height="22" forecolor="{line}"/></line>')
    add('    </band>')
    add('  </columnHeader>')
    add('')

    # DETAIL
    add('  <detail>')
    add('    <band height="19" splitType="Stretch">')
    add('      <rectangle>')
    add(f'        <reportElement x="0" y="0" width="802" height="19" backcolor="{stripe}" forecolor="{stripe}">')
    add('          <printWhenExpression><![CDATA[$V{ROW_NUMBER} % 2 == 0]]></printWhenExpression>')
    add('        </reportElement>')
    add('        <graphicElement><pen lineWidth="0.0"/></graphicElement>')
    add('      </rectangle>')
    add(f'      <line><reportElement x="0" y="18" width="802" height="1" forecolor="{rule}"/></line>')
    for i, (x0, w) in enumerate(zip(xs, widths)):
        add('      <textField textAdjust="StretchHeight">')
        add(f'        <reportElement x="{x0}" y="0" width="{w}" height="19" isPrintWhenDetailOverflows="true"/>')
        add('        <textElement textAlignment="Center" verticalAlignment="Middle"><font fontName="Cairo" size="7"/></textElement>')
        add(f'        <textFieldExpression><![CDATA[$P{{IS_RTL}} ? {cell_expression(mirrored[i])} : {cell_expression(cols[i])}]]></textFieldExpression>')
        add('      </textField>')
    for x0 in xs[1:]:
        add(f'      <line><reportElement x="{x0}" y="0" width="1" height="19" forecolor="{rule}"/></line>')
    add('    </band>')
    add('  </detail>')
    add('')

    # SUMMARY
    lines = spec.get("summaryLines") or ['$P{LBL_TOTAL_RECORDS} + ": " + $V{ROW_NUMBER}']
    height = 24 + 14 * (len(lines) - 1) + 16
    add('  <summary>')
    add(f'    <band height="{height}" splitType="Stretch">')
    add('      <rectangle>')
    add(f'        <reportElement x="0" y="0" width="802" height="24" backcolor="{line}" forecolor="{line}"/>')
    add('        <graphicElement><pen lineWidth="0.0"/></graphicElement>')
    add('      </rectangle>')
    add('      <textField>')
    add('        <reportElement x="0" y="0" width="802" height="24" forecolor="#FFFFFF"/>')
    add('        <textElement textAlignment="Center" verticalAlignment="Middle"><font fontName="Cairo" size="10" isBold="true"/></textElement>')
    add(f'        <textFieldExpression><![CDATA[{lines[0]}]]></textFieldExpression>')
    add('      </textField>')
    y = 26
    for extra in lines[1:]:
        add('      <textField>')
        add(f'        <reportElement x="0" y="{y}" width="802" height="13" forecolor="#2c3e50"/>')
        add('        <textElement textAlignment="Center" verticalAlignment="Middle"><font fontName="Cairo" size="8" isBold="true"/></textElement>')
        add(f'        <textFieldExpression><![CDATA[{extra}]]></textFieldExpression>')
        add('      </textField>')
        y += 14
    # AllSectionsNoDetail ignores a <noData> band, so "no data" is said here.
    add('      <textField>')
    add(f'        <reportElement x="0" y="{y}" width="802" height="12" forecolor="#7a3040">')
    add('          <printWhenExpression><![CDATA[$V{ROW_NUMBER} == null || $V{ROW_NUMBER} == 0]]></printWhenExpression>')
    add('        </reportElement>')
    add('        <textElement textAlignment="Center" verticalAlignment="Middle"><font fontName="Cairo" size="8"/></textElement>')
    add('        <textFieldExpression><![CDATA[$P{LBL_NO_DATA}]]></textFieldExpression>')
    add('      </textField>')
    add('    </band>')
    add('  </summary>')
    add('</jasperReport>')
    return "\n".join(out) + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    spec = json.load(open(sys.argv[1], encoding="utf-8"))
    target = os.path.join(REPORTS_DIR, spec["name"] + ".jrxml")
    with open(target, "w", encoding="utf-8", newline="") as fh:
        fh.write(build(spec))
    print(f"wrote {os.path.relpath(target)}  ({len(spec['columns'])} columns)")
    print("now run: python scripts/apply_official_layout.py " + os.path.relpath(target))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
